#!/usr/bin/env python3
# coding: utf-8
"""
verify_mesh_html.py — load the mesh observability view in a real browser.

Why this exists
---------------
`graphify-out/mesh_gephi_interactive.html` is the only interactive view of the
mesh, and it is generated by templating JSON into vis.js. That makes it an
artifact nobody *checks*: the generator can emit an edge whose endpoints are
not nodes, vis.js drops it silently, and the page still renders, still looks
populated, and still reports success.

That is exactly what happened. A learned route key (`route:windows>mesh`) was
drawn as an edge from `nature:route` to `windows>mesh` — neither exists — so the
route telemetry was invisible in the graph, with nothing raised anywhere. A
generator that cannot fail is not verification.

So this script does not read the generator's counters. It boots headless Chrome,
loads the page, and asks the browser what it actually built, while capturing
console errors and uncaught exceptions.

Why raw CDP instead of Playwright
---------------------------------
Playwright cannot run here at all: both its sync and async entry points import
`greenlet`, whose C extension in this installation is a GIL build
(`_greenlet.cp314-win_amd64.pyd`) while the mandated interpreter is free-threaded
3.14t. That is the same failure class as `cryptography`'s `serialization`
segfault (see NEURAL_MESH_GAP_AUDIT §6.1): a GIL-only native extension inside a
3.14t process. Driving CDP directly needs only `websocket-client`, which is a
pure-Python dependency that is already installed — so verification adds no
native dependency of its own.

Usage:
    python tools/verify_mesh_html.py            # verify (exit 1 on failure)
    python tools/verify_mesh_html.py --headful  # watch it render
"""

import argparse
import json
import os
import shutil
import subprocess
import sys
import tempfile
import time
import urllib.request
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parent.parent
HTML = PROJECT_ROOT / "graphify-out" / "mesh_gephi_interactive.html"
MANIFEST = PROJECT_ROOT / "graphify-out" / "mesh_gephi_interactive.json"

CHROME_CANDIDATES = (
    r"C:\Program Files\Google\Chrome\Application\chrome.exe",
    r"C:\Program Files (x86)\Google\Chrome\Application\chrome.exe",
    "/usr/bin/google-chrome",
    "/usr/bin/chromium",
    "/usr/bin/chromium-browser",
    "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome",
)


def find_chrome() -> str:
    env = os.environ.get("CHROME_PATH")
    if env and Path(env).exists():
        return env
    for cand in CHROME_CANDIDATES:
        if Path(cand).exists():
            return cand
    found = shutil.which("chrome") or shutil.which("google-chrome") or shutil.which("chromium")
    if found:
        return found
    raise RuntimeError("no Chrome/Chromium found; set CHROME_PATH")


def launch(profile_dir: str, headful: bool) -> subprocess.Popen:
    args = [
        find_chrome(),
        "--remote-debugging-port=0",
        f"--user-data-dir={profile_dir}",
        "--no-first-run", "--no-default-browser-check",
        "--disable-extensions", "--disable-background-networking",
        "--disable-sync", "--disable-gpu", "--mute-audio",
        # Chrome 111+ rejects CDP websocket handshakes from non-browser
        # origins unless this is set; without it every connection 403s.
        "--remote-allow-origins=*",
        "about:blank",
    ]
    if not headful:
        args.insert(1, "--headless=new")
    return subprocess.Popen(args, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)


def wait_for_endpoint(profile_dir: str, timeout: float = 30.0) -> str:
    port_file = Path(profile_dir) / "DevToolsActivePort"
    deadline = time.time() + timeout
    while time.time() < deadline:
        if port_file.exists():
            lines = port_file.read_text(encoding="utf-8").splitlines()
            if lines and lines[0].strip():
                return f"http://127.0.0.1:{lines[0].strip()}"
        time.sleep(0.2)
    raise RuntimeError(f"Chrome never published {port_file}")


class CDP:
    """Minimal Chrome DevTools Protocol client over websocket-client."""

    def __init__(self, ws_url: str):
        import websocket  # websocket-client
        self._ws = websocket.create_connection(ws_url, timeout=30)
        self._id = 0
        self.events: list = []

    def send(self, method: str, params: dict | None = None, session: str | None = None) -> int:
        self._id += 1
        msg = {"id": self._id, "method": method, "params": params or {}}
        if session:
            msg["sessionId"] = session
        self._ws.send(json.dumps(msg))
        return self._id

    def _recv_until(self, msg_id: int, timeout: float = 30.0) -> dict:
        deadline = time.time() + timeout
        while time.time() < deadline:
            self._ws.settimeout(max(0.5, deadline - time.time()))
            try:
                msg = json.loads(self._ws.recv())
            except Exception:
                continue
            if msg.get("id") == msg_id:
                return msg
            if "method" in msg:
                self.events.append(msg)
        raise TimeoutError(f"no reply to id={msg_id}")

    def call(self, method: str, params: dict | None = None, session: str | None = None,
             timeout: float = 30.0) -> dict:
        return self._recv_until(self.send(method, params, session), timeout)

    def drain(self, seconds: float = 1.5) -> None:
        """Collect any events that arrive in the next `seconds`."""
        deadline = time.time() + seconds
        while time.time() < deadline:
            self._ws.settimeout(max(0.1, deadline - time.time()))
            try:
                msg = json.loads(self._ws.recv())
            except Exception:
                continue
            if "method" in msg:
                self.events.append(msg)

    def close(self) -> None:
        try:
            self._ws.close()
        except Exception:
            pass


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--headful", action="store_true", help="show the browser window")
    ap.add_argument("--timeout", type=float, default=25.0,
                    help="seconds to wait for the graph to initialise")
    ap.add_argument("--html", type=Path, default=HTML,
                    help="check a specific artifact (also enables negative controls)")
    ap.add_argument("--manifest", type=Path, default=MANIFEST,
                    help="manifest to cross-check against")
    args = ap.parse_args()
    html_path = args.html if args.html.is_absolute() else (PROJECT_ROOT / args.html)
    manifest_path = args.manifest if args.manifest.is_absolute() else (PROJECT_ROOT / args.manifest)

    if not html_path.exists():
        print(f"FAIL: {html_path} does not exist — run tools/gephi_mesh_pipeline.py --html --json")
        return 1

    try:
        import websocket  # noqa: F401  (websocket-client, pure Python)
    except ImportError:
        print("SKIP: websocket-client is not installed (pip install websocket-client)")
        return 2

    profile = tempfile.mkdtemp(prefix="meshverify_")
    proc = launch(profile, args.headful)
    problems: list = []
    console_errors: list = []
    page_errors: list = []
    rendered = None
    canvas_ok = False
    title = ""
    diagnostics: dict = {}

    try:
        base = wait_for_endpoint(profile)
        with urllib.request.urlopen(f"{base}/json/version", timeout=10) as resp:
            ws_url = json.loads(resp.read())["webSocketDebuggerUrl"]

        cdp = CDP(ws_url)
        try:
            target_id = cdp.call("Target.createTarget",
                                 {"url": html_path.as_uri()})["result"]["targetId"]
            session = cdp.call("Target.attachToTarget",
                               {"targetId": target_id, "flatten": True})["result"]["sessionId"]

            for method in ("Runtime.enable", "Log.enable", "Page.enable"):
                cdp.call(method, session=session)

            # Poll for the page's own readiness handle.
            deadline = time.time() + args.timeout
            while time.time() < deadline:
                res = cdp.call("Runtime.evaluate", {
                    "expression": "!!(window.__mesh && window.__mesh.ready)",
                    "returnByValue": True,
                }, session=session, timeout=10)
                if res.get("result", {}).get("result", {}).get("value"):
                    break
                time.sleep(0.25)
            cdp.drain(1.0)

            # NB: an IIFE, not an arrow function. `Runtime.evaluate` with
            # `returnByValue` on an arrow function serialises the *function*,
            # not its result, so the check silently sees null and reports a
            # failure that is really a harness bug.
            expr = ("(function(){var d=window.__mesh; if(!d) return null;"
                    " return {nodes:d.nodes, edges:d.edges, nodeIds:d.nodeIds,"
                    " edgeRefs:d.edgeRefs,"
                    " canvas:!!document.querySelector('#graph canvas'),"
                    " title:document.title, href:location.href,"
                    " readyState:document.readyState,"
                    " visType:typeof vis};})()")
            res = cdp.call("Runtime.evaluate", {"expression": expr, "returnByValue": True},
                           session=session, timeout=15)
            payload = res.get("result", {}).get("result", {}).get("value")
            if payload:
                rendered = payload
                canvas_ok = bool(payload.get("canvas"))
                title = payload.get("title", "")
            # Always capture why, so a failure explains itself rather than
            # only reporting that a handle was missing.
            diag = cdp.call("Runtime.evaluate", {
                "expression": "(function(){return {href:location.href,"
                              " readyState:document.readyState,"
                              " visType:typeof vis, meshType:typeof window.__mesh};})()",
                "returnByValue": True,
            }, session=session, timeout=10)
            diagnostics = diag.get("result", {}).get("result", {}).get("value") or {}

            # Translate the collected protocol events. Without this the
            # harness reports "0 console errors" while the page is throwing:
            # an unread error channel looks exactly like a clean one.
            for ev in cdp.events:
                method = ev.get("method", "")
                params = ev.get("params", {}) or {}
                if method == "Runtime.exceptionThrown":
                    det = params.get("exceptionDetails", {}) or {}
                    exc = det.get("exception", {}) or {}
                    page_errors.append(exc.get("description") or det.get("text") or "exception")
                elif method == "Runtime.consoleAPICalled":
                    if params.get("type") in ("error", "warning"):
                        text = " ".join(
                            str(a.get("value", a.get("description", "")))
                            for a in params.get("args", [])
                        )
                        if "favicon" not in text:
                            console_errors.append(f"{params.get('type')}: {text}")
                elif method == "Log.entryAdded":
                    entry = params.get("entry", {}) or {}
                    if entry.get("level") in ("error", "warning"):
                        text = f"{entry.get('source', '')}: {entry.get('text', '')}"
                        if "favicon" not in text:
                            console_errors.append(text)
        finally:
            cdp.close()
    except Exception as exc:
        problems.append(f"browser harness error: {type(exc).__name__}: {exc}")
    finally:
        proc.terminate()
        try:
            proc.wait(timeout=10)
        except Exception:
            proc.kill()
        shutil.rmtree(profile, ignore_errors=True)

    # Console errors are failures. A page that renders while complaining about
    # its own inputs is exactly the state this view was in before: vis.js
    # rejected an invalid option and nothing anywhere reported it.
    problems.extend(f"console: {e.splitlines()[0][:140]}" for e in console_errors)

    if rendered is None:
        problems.append("the graph never initialised (window.__mesh was never set)")
        if diagnostics:
            problems.append(f"  page was at {diagnostics.get('href')!r}, "
                            f"readyState={diagnostics.get('readyState')!r}, "
                            f"typeof vis={diagnostics.get('visType')!r}, "
                            f"typeof __mesh={diagnostics.get('meshType')!r}")

    # The check the generator cannot fake: could the browser resolve every edge?
    unresolved: list = []
    if rendered:
        ids = set(rendered["nodeIds"])
        unresolved = [[a, b] for a, b in rendered["edgeRefs"] if a not in ids or b not in ids]
        if unresolved:
            problems.append(f"{len(unresolved)} edge(s) reference missing nodes: {unresolved[:5]}")
        if not rendered["nodes"] or not rendered["edges"]:
            problems.append(f"graph is empty: {rendered['nodes']} nodes, {rendered['edges']} edges")
    if not canvas_ok and rendered is not None:
        problems.append("no <canvas> rendered inside #graph")

    manifest = None
    if manifest_path.exists():
        manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
        if rendered:
            if manifest["nodes"] != rendered["nodes"]:
                problems.append(f"manifest says {manifest['nodes']} nodes, browser built "
                                f"{rendered['nodes']}")
            if manifest["edges"] != rendered["edges"]:
                problems.append(f"manifest says {manifest['edges']} edges, browser built "
                                f"{rendered['edges']}")
        if manifest.get("unresolved_edges"):
            problems.append(f"manifest reports {manifest['unresolved_edges']} unresolved edges "
                            f"at generation time")

    print("Mesh HTML view — headless Chrome verification (raw CDP)")
    print("=" * 56)
    print(f"  file      : {html_path.name}")
    print(f"  title     : {title}")
    if rendered:
        print(f"  nodes     : {rendered['nodes']}")
        print(f"  edges     : {rendered['edges']}")
        print(f"  canvas    : {'yes' if canvas_ok else 'NO'}")
        print(f"  unresolved: {len(unresolved)}")
    if manifest:
        print(f"  routes    : {len(manifest.get('route_edges', []))} route edges drawn")
    print(f"  console   : {len(console_errors)} error/warning")
    for msg in console_errors[:5]:
        print(f"      {msg[:160]}")
    print(f"  pageerror : {len(page_errors)}")
    for msg in page_errors[:5]:
        print(f"      {msg[:160]}")

    if problems:
        print("\nFAIL")
        for p in problems:
            print(f"  - {p}")
        return 1

    print("\nPASS — the browser built the graph and every edge resolved to a real node.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
