# coding: utf-8
"""Count open items in a tracking document -- or refuse to.

WHY THIS EXISTS (measured, not theorised). Tracking items were closed by counting
``- [ ]`` in files that do not use checkboxes. The count came back 0 and 0 was read
as "nothing open". Measured on the tree at HEAD ``3191c3ff``:

  * ``MASTER_CAPABILITY_TODO.md`` holds **0** ``- [ ]`` and **133** open rows marked
    ``U+2B1C`` (open square), the glyph its own legend defines at L6. A checkbox
    census reports "nothing open" for a document whose legend says 133 rows are
    not started.
  * ``PLATFORM_DEPLOYMENT.md`` uses ``U+1F534/U+1F7E1/U+1F7E2``, so even a
    ``U+2B1C``-aware checker returns 0 on it. TWO glyph vocabularies are in use
    and neither is declared.
  * ``TODO_315T_BUILD.md`` defaults to OPEN: a table row is owed unless it carries a
    ``DONE`` token. A marker-based counter returns 0 for a file whose silence means
    owed -- the maximum reported as the minimum.

So the defect is not a wrong number. It is a *valid instrument applied to the wrong
convention*, and the fix is to make the convention part of the answer.

THE INVARIANT THIS FILE EXISTS TO ENFORCE: a file whose convention could not be
detected is reported ``UNPARSED`` and exits non-zero. It is never reported as
``0 open``. Absence of a recognised marker is not evidence of completion.

BASES RECOGNISED (detected from the BODY, never from a header's claim -- see below):

  * ``checkbox``       ``- [ ]`` open, ``- [x]`` done, on list items.
  * ``status-glyph``   a glyph in a TABLE ROW. Two vocabularies, both counted:
                       ``U+2B1C``/``U+26A0``/``U+2705`` and
                       ``U+1F534``/``U+1F7E1``/``U+1F7E2``. One row is one
                       item; the status is the row's FIRST glyph. Further glyphs in
                       the same row are reported as ``extra_glyph_cells`` and are
                       never added to the row count -- a platform matrix row carries
                       four glyphs across four different columns, and counting all
                       four would inflate the file fourfold.
  * ``implicit-open``  a table row whose first cell is an identifier (``**G-4**``,
                       ``AR-5``). The row is DONE only if it contains a ``DONE``
                       token; otherwise it is OPEN. The token's column is NOT fixed
                       -- in ``TODO_315T_BUILD.md`` G-4 carries ``**DONE**`` in its
                       Est. cell while T-16 carries ``**DONE 2026-10-10`` inside its
                       TASK cell -- so the whole row is searched, not one cell.

A document may use several of these at once (``CODEBASE_AUDIT_TODO.md`` uses all
three). No single "open" number is printed for such a file; each basis is reported
with its own count and any cross-basis total is labelled a SUM, with the number of
rows carrying two bases reported beside it so the sum cannot be mistaken for a
census.

WHY THE HEADER IS NOT TRUSTED. ``NEURAL_MESH_BRAINSTEM_TODO.md`` L34 states "Each
item is a checkbox". Its body contains no checkbox; items are EVIDENCE/CLAIM prose.
Stated convention != actual convention, so detection probes the body.

WHY NOTHING IS EXECUTED. This reads text and counts. It does not know whether an
item SHOULD be done, and it does not decide closures: it reports the basis with the
number (``133 open (glyph U+2B1C)``) so a reader can falsify the basis independently --
which is what every falsified closure on record lacked.

CLI:
    python tools/closure_basis_check.py FILE...          # human-readable
    python tools/closure_basis_check.py --json FILE...   # machine-readable

Exit codes:
    0  every file was parsed (whether or not items are open)
    2  at least one file was UNPARSED or MISSING, or the arguments were bad

A parsed file with items open still exits 0: "there is work owed" is not a failure
of this tool. Non-zero means *the measurement failed*, and that distinction is the
whole point -- a checker that conflates "cannot measure" with "nothing owed" is the
defect it is meant to prevent.
"""

from __future__ import annotations

import argparse
import json
import re
from pathlib import Path
from typing import Any, Dict, List, Optional, Sequence, Set, Tuple

#: A file with fewer non-blank lines than this and no recognised basis is a stub,
#: not an unparsed document. Above it, "no markers found" is a measurement failure.
STUB_NONBLANK = 8

#: Only the head of a file is inspected for a generated-by banner; a mention of
#: "generated by" in the body of a plan document describes a generator, it does not
#: make the document generated.
GENERATED_HEAD_LINES = 15

CHECKBOX = re.compile(r"^\s*[-*+]\s+\[(?P<mark>[ xX])\]\s")
TABLE_ROW = re.compile(r"^\s*\|")

#: `| **G-4** |` and `| AR-5 |`. Deliberately does NOT match `| 1.1 |` or `| 8 |`:
#: MASTER_CAPABILITY_TODO and CODEBASE_AUDIT_TODO number their rows, and treating
#: those as implicit-open items would double-count every glyph row in both files.
ROW_ID = re.compile(r"^\|\s*\*{0,2}[A-Z][A-Z0-9]{0,4}-\d+\*{0,2}\s*\|")

DONE_TOKEN = re.compile(r"\bDONE\b")

#: Strong banners only. "regenerate" was rejected as a trigger: it appears in prose
#: describing a generator, and a false positive here SUPPRESSES a real count.
GENERATED_BANNER = re.compile(
    r"(?i)(\bgenerated by\b|\bauto-?generated\b|\bdo not edit this file\b)")

DECLARED_TOTAL = re.compile(r"(?i)\btotal items\b\**\s*[:=]\s*\**\s*(\d+)")

#: Placeholders that mark a TEMPLATE rather than owed work (a contributing
#: checklist, a changelog entry form). Reported as a suspicion, never used to
#: change a count.
PLACEHOLDER = re.compile(
    r"\[(?:\+?N lines?|\+?N|file|filename|description|name|date)\]")

#: U+FE0F is the emoji variation selector. U+26A0 followed by U+FE0F is two code
#: points and U+26A0 alone is one; stripping it lets both spellings resolve to the
#: same glyph instead of one being silently invisible to the counter.
_VARIATION_SELECTOR = "\ufe0f"

_GLYPHS: Dict[str, Tuple[str, str]] = {}


def _register(vocabulary: str, char: str, meaning: str) -> None:
    _GLYPHS[char] = (vocabulary, meaning)


# Vocabulary 1 -- MASTER_CAPABILITY_TODO.md L6: "U+2705 = Done, U+2B1C = Not
# started, U+26A0 (U+FE0F variant) = In progress/Blocked".
_register("square", "\u2b1c", "not_started")
_register("square", "\u26a0", "in_progress")
_register("square", "\u2705", "done")

# Vocabulary 2 -- PLATFORM_DEPLOYMENT.md: "U+1F534 Not started / U+1F7E1 Explored /
# U+1F7E2 Active".
_register("traffic-light", "\U0001f534", "not_started")
_register("traffic-light", "\U0001f7e1", "in_progress")
_register("traffic-light", "\U0001f7e2", "done")


def _strip_variation(text: str) -> str:
    """Drop the emoji variation selector so both spellings of a glyph match."""
    return text.replace(_VARIATION_SELECTOR, "")


def is_generated(lines: Sequence[str]) -> bool:
    """True when the head of the file declares itself generated."""
    for line in lines[:GENERATED_HEAD_LINES]:
        if GENERATED_BANNER.search(line):
            return True
    return False


def declared_total(lines: Sequence[str]) -> Optional[Dict[str, Any]]:
    """Find a count the file states about itself, e.g. ``**Total items:** 98``."""
    for index, line in enumerate(lines):
        match = DECLARED_TOTAL.search(line)
        if match is None:
            continue
        return {"value": int(match.group(1)), "line": index + 1}
    return None


def template_suspicion(lines: Sequence[str]) -> List[str]:
    """Distinct placeholder tokens that suggest a template rather than a task list."""
    seen: Set[str] = set()
    for line in lines:
        for token in PLACEHOLDER.findall(line):
            seen.add(token.lower())
    return sorted(seen)


def analyse(text: str) -> Dict[str, Any]:
    """Detect every basis present in `text` and count each independently."""
    lines = text.splitlines()
    normalized = [_strip_variation(line) for line in lines]
    bases: Dict[str, Dict[str, Any]] = {}

    # ── checkbox ────────────────────────────────────────────────────────────
    open_lines: List[int] = []
    done_lines: List[int] = []
    for index, line in enumerate(lines):
        match = CHECKBOX.match(line)
        if match is None:
            continue
        if match.group("mark").lower() == "x":
            done_lines.append(index + 1)
        else:
            open_lines.append(index + 1)
    if open_lines or done_lines:
        bases["checkbox"] = {
            "rule": "`- [ ]` is open, `- [x]` is done (list-item checkbox)",
            "open": len(open_lines),
            "done": len(done_lines),
            "open_lines": open_lines,
            "done_lines": done_lines,
            "lines": sorted(open_lines + done_lines),
        }

    # ── status glyph (table rows only) ──────────────────────────────────────
    meanings = {"not_started": 0, "in_progress": 0, "done": 0}
    glyph_lines: List[int] = []
    vocabularies: Set[str] = set()
    extra_cells = 0
    for index, row in enumerate(normalized):
        if TABLE_ROW.match(row) is None:
            continue
        found: List[Tuple[str, str]] = []
        for char in row:
            hit = _GLYPHS.get(char)
            if hit is not None:
                found.append(hit)
        if not found:
            continue
        vocabulary, meaning = found[0]
        vocabularies.add(vocabulary)
        meanings[meaning] += 1
        glyph_lines.append(index + 1)
        extra_cells += len(found) - 1
    if glyph_lines:
        bases["status-glyph"] = {
            "rule": ("one table row is one item; status is the row's first glyph "
                     "(U+2B1C/U+26A0/U+2705 or U+1F534/U+1F7E1/U+1F7E2); "
                     "open = not started + in progress"),
            "open": meanings["not_started"] + meanings["in_progress"],
            "done": meanings["done"],
            "not_started": meanings["not_started"],
            "in_progress": meanings["in_progress"],
            "vocabulary": sorted(vocabularies),
            "extra_glyph_cells": extra_cells,
            "glyph_lines": glyph_lines,
            "lines": glyph_lines,
        }

    # ── implicit open (unmarked identifier row == owed) ─────────────────────
    implicit_open: List[int] = []
    implicit_done: List[int] = []
    for index, row in enumerate(lines):
        if TABLE_ROW.match(row) is None or ROW_ID.match(row) is None:
            continue
        if DONE_TOKEN.search(row):
            implicit_done.append(index + 1)
        else:
            implicit_open.append(index + 1)
    if implicit_open or implicit_done:
        bases["implicit-open"] = {
            "rule": ("a table row keyed by an identifier is OWED unless the row "
                     "carries a DONE token (the token's column is not fixed)"),
            "open": len(implicit_open),
            "done": len(implicit_done),
            "open_lines": implicit_open,
            "done_lines": implicit_done,
            "lines": sorted(implicit_open + implicit_done),
        }

    # ── cross-basis overlap: rows that belong to more than one basis ────────
    memberships: Dict[int, int] = {}
    for base in bases.values():
        for line_number in set(base["lines"]):
            memberships[line_number] = memberships.get(line_number, 0) + 1
    overlap_rows = sum(1 for count in memberships.values() if count > 1)

    nonblank = sum(1 for line in lines if line.strip())
    return {
        "bases": bases,
        "overlap_rows": overlap_rows,
        "declared": declared_total(lines),
        "template_tokens": template_suspicion(lines),
        "generated": is_generated(lines),
        "nonblank": nonblank,
        "line_count": len(lines),
    }


def classify(path: Path) -> Dict[str, Any]:
    """Analyse one file and assign the status that decides the exit code."""
    record: Dict[str, Any] = {"path": str(path), "bases": {}}

    if not path.is_file():
        record["status"] = "MISSING"
        record["note"] = "file not found -- a missing file is not an open count"
        return record

    raw = path.read_bytes()
    text = raw.decode("utf-8", errors="replace").replace("\r\n", "\n")
    analysis = analyse(text)

    for key in ("bases", "overlap_rows", "declared", "template_tokens",
                "nonblank", "line_count"):
        record[key] = analysis[key]

    if analysis["generated"]:
        record["status"] = "GENERATED"
        record["counts_suppressed"] = True
        record["note"] = ("file declares itself generated -- re-run its generator; "
                          "counting it measures the last run, not the tree")
        return record

    if not analysis["bases"]:
        if analysis["nonblank"] <= STUB_NONBLANK:
            record["status"] = "STUB"
            record["note"] = "too short to carry items; no basis and nothing to owe"
        else:
            record["status"] = "UNPARSED"
            # Deliberately avoids the words a reader would quote as a finding:
            # the string must not be greppable as a measured zero.
            record["note"] = (
                "no basis detected in a %d-line document; the convention was not "
                "recognised, so NO count is reported -- a zero here would be a "
                "claim about a convention nobody detected"
                % analysis["nonblank"])
        return record

    record["status"] = "MIXED" if len(analysis["bases"]) > 1 else "PARSED"
    record["open_sum_across_bases"] = sum(
        base["open"] for base in analysis["bases"].values())
    return record


def _describe(record: Dict[str, Any]) -> List[str]:
    """Render one record as human-readable lines, always naming the basis."""
    status = record["status"]
    path = record["path"]

    if status == "MISSING":
        return ["%s: MISSING -- %s" % (path, record["note"])]
    if status == "GENERATED":
        return ["%s: GENERATED -- %s" % (path, record["note"])]
    if status == "STUB":
        return ["%s: STUB -- %s" % (path, record["note"])]
    if status == "UNPARSED":
        return ["%s: UNPARSED -- %s" % (path, record["note"])]

    bases: Dict[str, Dict[str, Any]] = record["bases"]
    out: List[str] = []

    if status == "PARSED":
        name = next(iter(bases))
        base = bases[name]
        if name == "status-glyph":
            out.append("%s: %d open (glyph %s) = %d not started + %d in progress; "
                       "%d done"
                       % (path, base["open"], "/".join(base["vocabulary"]),
                          base["not_started"], base["in_progress"], base["done"]))
            if base["extra_glyph_cells"]:
                out.append("    %d further glyph cell(s) in the same rows, not "
                           "counted (one row = one item)"
                           % base["extra_glyph_cells"])
        else:
            out.append("%s: %d open, %d done (%s)"
                       % (path, base["open"], base["done"], name))
    else:
        out.append("%s: MIXED -- %d bases; no single open count is printed"
                   % (path, len(bases)))
        for name in sorted(bases):
            base = bases[name]
            out.append("    %-14s %3d open / %3d done" % (name, base["open"],
                                                         base["done"]))
        out.append("    sum across bases = %d open. LABELLED SUM, not a per-file "
                   "count: %d row(s) carry more than one basis."
                   % (record["open_sum_across_bases"], record["overlap_rows"]))

    declared = record.get("declared")
    if declared:
        counted_lines = sorted({ln for base in bases.values()
                                for ln in base["lines"]})
        delta = len(counted_lines) - declared["value"]
        verdict = "agrees" if delta == 0 else "DISAGREES by %d" % delta
        out.append("    file declares a total of %d at line %d; %d item line(s) "
                   "counted -- %s (both are shown, neither is resolved here)"
                   % (declared["value"], declared["line"], len(counted_lines),
                      verdict))

    tokens = record.get("template_tokens") or []
    if len(tokens) >= 2:
        out.append("    template suspected (placeholders: %s) -- a checklist to "
                   "fill in is not owed work; the count above was NOT adjusted"
                   % ", ".join(tokens))

    return out


def main(argv: Optional[Sequence[str]] = None) -> int:
    parser = argparse.ArgumentParser(
        prog="closure_basis_check.py",
        description=("Count open items in tracking documents, naming the convention "
                     "used, or refuse to count (UNPARSED) when the convention cannot "
                     "be detected."))
    parser.add_argument("paths", nargs="+", metavar="FILE",
                        help="tracking document(s) to check")
    parser.add_argument("--json", action="store_true",
                        help="emit one JSON object instead of text")
    args = parser.parse_args(list(argv) if argv is not None else None)

    records = [classify(Path(p)) for p in args.paths]
    failed = [r for r in records if r["status"] in ("UNPARSED", "MISSING")]

    if args.json:
        print(json.dumps({"files": records, "unparsed": len(failed)},
                         indent=2, sort_keys=True, default=str))
    else:
        for record in records:
            for line in _describe(record):
                print(line)
        print("")
        parsed = len(records) - len(failed)
        print("closure_basis_check: %d file(s), %d parsed, %d unparsed or missing"
              % (len(records), parsed, len(failed)))
        if failed:
            print("  A file in this list has NO measured count -- its convention "
                  "was not recognised, or it is absent. Fix the input or teach "
                  "the checker.")
        else:
            print("  Every file's convention was detected; each count above names "
                  "the basis it used.")

    return 2 if failed else 0


if __name__ == "__main__":
    raise SystemExit(main())
