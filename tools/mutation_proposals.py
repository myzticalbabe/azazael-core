#!/usr/bin/env python3
# coding: utf-8
"""MUTATION-PROPOSALS -- turn the census findings into a queue the harness can work.

The mutator had no *input*. `tools/self_modify.py` can apply, evaluate and
revert a patch, but nothing was proposing patches, so the loop was still
human-driven at exactly the point that matters. This reads the census findings
and writes one proposal per finding to logs/mutation_queue.jsonl.

What it deliberately does NOT do: write patches. A proposal says what evidence
exists and what would have to be true to close it. Turning that into a patch is
a code-generation step, and a generator that also decides correctness would
collapse propose and evaluate into one actor -- the failure mode that produced a
fitness function whose optimum was "set every gene to 1.0".

Schema tolerance is intentional. The census artifacts are regenerated by other
tools and their key names have changed before; guessing a schema and crashing on
a rename would make this useless exactly when it is needed. Fields are matched by
name with fallbacks, and anything unrecognised is carried through verbatim in
`evidence` rather than dropped.

    python tools/mutation_proposals.py            # write the queue
    python tools/mutation_proposals.py --summary  # counts only, no writes
"""

from __future__ import annotations

import argparse
import json
from collections import Counter
from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Iterable, Sequence

ROOT = Path(__file__).resolve().parents[1]
WIRE_NAME = "NEURAL_MESH_WIRE_OR_CUT.json"
MAP_NAME = "NEURAL_MESH_INTEGRATION_MAP.json"
SOURCES = (WIRE_NAME, MAP_NAME)
QUEUE = ROOT / "logs" / "mutation_queue.jsonl"

NAME_KEYS = ("function", "name", "func", "qualname", "symbol", "id")
FILE_KEYS = ("file", "path", "module", "filepath", "source", "location")
NATURE_KEYS = ("nature", "category", "owner", "stage", "role")
VERDICT_KEYS = ("verdict", "status", "decision", "action", "reason")


def _pick(row: dict, keys: Iterable[str], default: str = "") -> str:
    for k in keys:
        v = row.get(k)
        if isinstance(v, str) and v.strip():
            return v.strip()
        if isinstance(v, (int, float)):
            return str(v)
    return default


def _looks_like_id(key: Any) -> bool:
    """Is this dict key an identity, or is it metadata?

    The first version required BOTH ':' and '.', which silently dropped the 35
    `module_level` findings: those are keyed by module path, not by
    `nature:Class.method`, so they never reached a proposal row at all and the
    control showed a bucket that could not be matched. A findings block is keyed
    by identity throughout, so paths and dotted names count too.
    """
    if not isinstance(key, str) or not key.strip():
        return False
    return any(sep in key for sep in (":", ".", "/", "\\"))


def _id_keyed(obj: Any, path: str = "") -> list[tuple[str, dict]]:
    """Dicts whose KEYS are the identities.

    This is how the census actually stores them: `declared` and `findings` are
    both keyed "nature:Class.method". A walker that only looked at row *fields*
    emitted zero proposals against the real artifacts, so key-shaped identity is
    treated as identity in its own right.
    """
    found: list[tuple[str, dict]] = []
    if isinstance(obj, dict):
        ids = {k: v for k, v in obj.items() if _looks_like_id(k)}
        if ids:
            found.append((path, ids))
        for k, v in obj.items():
            if isinstance(v, (dict, list)):
                found.extend(_id_keyed(v, "%s.%s" % (path, k) if path else str(k)))
    elif isinstance(obj, list):
        for i, v in enumerate(obj):
            found.extend(_id_keyed(v, "%s[%d]" % (path, i)))
    return found


def _rows(obj: Any, path: str = "") -> list[tuple[str, dict]]:
    """Every dict in the document, wherever the needles are nested."""
    found: list[tuple[str, dict]] = []
    if isinstance(obj, dict):
        if obj and all(not isinstance(v, (dict, list)) for v in obj.values()):
            found.append((path, obj))
        for k, v in obj.items():
            found.extend(_rows(v, "%s.%s" % (path, k) if path else k))
    elif isinstance(obj, list):
        for i, v in enumerate(obj):
            found.extend(_rows(v, "%s[%d]" % (path, i)))
    return found


def _walk_ids(val: Any) -> list[tuple[str, Any]]:
    found: list[tuple[str, Any]] = []
    if isinstance(val, dict):
        for k, v in val.items():
            if _looks_like_id(k):
                found.append((k, v))
            else:
                found.extend(_walk_ids(v))
    elif isinstance(val, list):
        for v in val:
            found.extend(_walk_ids(v))
    elif isinstance(val, str) and _looks_like_id(val):
        found.append((val, None))
    return found


DISPOSITION_KEYS = ("disposition", "verdict", "status", "resolution",
                    "action", "decision", "state")


def _counts() -> dict[str, int]:
    """The map's disposition buckets, used as a CONTROL rather than an input.

    Measured 2026-09-18: they are integers -- {"unresolved": int,
    "wire_at_site": int, ...}. There is no id -> disposition mapping in that
    block at all, which is why the first join missed every row and all 428 read
    "review". They still earn their place: the histogram this file derives has
    to agree with them, and if it does not, the join is wrong and the control
    says so instead of the queue quietly lying.
    """
    doc = _load(MAP_NAME)
    return {k: v for k, v in (doc.get("dispositions") or {}).items()
            if isinstance(v, int)}


def _load(name: str) -> dict:
    src = ROOT / name
    if not src.is_file():
        return {}
    try:
        doc = json.loads(src.read_text(encoding="utf-8", errors="replace"))
    except ValueError:
        return {}
    return doc if isinstance(doc, dict) else {}


def _dispositions() -> dict[str, str]:
    """id -> disposition, read from the finding payloads themselves.

    The buckets are counts, so the per-finding disposition has to come from the
    finding. Without it every row reads "review" and the queue cannot say which
    findings are actionable -- and a queue that cannot prioritise is a list.
    """
    out: dict[str, str] = {}
    for name, field in ((MAP_NAME, "findings"), (WIRE_NAME, "declared")):
        for ident, payload in (_load(name).get(field) or {}).items():
            if not _looks_like_id(ident):
                continue
            if isinstance(payload, dict):
                found = _pick(payload, DISPOSITION_KEYS)
                if found:
                    out[ident] = found.lower()
            elif isinstance(payload, str) and payload.strip():
                out[ident] = payload.strip().lower()
    return out


def build() -> list[dict]:
    proposals: list[dict] = []
    disp = _dispositions()
    for name in SOURCES:
        src = ROOT / name
        if not src.is_file():
            continue
        try:
            doc = json.loads(src.read_text(encoding="utf-8", errors="replace"))
        except ValueError:
            continue
        rows: list[tuple[str, str, str, str, dict]] = []
        for path, mapping in _id_keyed(doc):
            for ident, payload in mapping.items():
                nature, _, symbol = ident.partition(":")
                verdict = "declared"
                target = "unknown"
                if isinstance(payload, dict):
                    verdict = _pick(payload, VERDICT_KEYS, "declared").lower()
                    target = _pick(payload, FILE_KEYS, "unknown")
                elif isinstance(payload, str) and payload.strip():
                    verdict = payload.strip().lower()
                rows.append((ident, symbol or ident, nature or "unassigned",
                             verdict, {"target": target, "evidence": payload}))
        for path, row in _rows(doc):
            fn = _pick(row, NAME_KEYS)
            if fn:
                rows.append((fn, fn, _pick(row, NATURE_KEYS, "unassigned"),
                             _pick(row, VERDICT_KEYS, "unstated").lower(), row))

        for ident, symbol, nature, verdict, detail in rows:
            # Disposition resolution, in order of trust. The row's OWN evidence
            # payload is read first: it demonstrably carries 'disposition'
            # (measured on a real finding), and two earlier attempts that relied
            # on the id-keyed join alone produced 428/428 "review" while the
            # control showed declared={wire_at_site: 33, integrate_via_stage: 92,
            # ...} -- so the join was not reaching these rows. Reading the
            # payload the row was built from cannot miss for that reason.
            joined = None
            evidence = detail.get("evidence")
            if isinstance(evidence, dict):
                joined = _pick(evidence, DISPOSITION_KEYS)
            if not joined:
                joined = disp.get(ident)
            if joined:
                verdict = joined.lower()
                detail = {"target": detail.get("target"), "disposition": verdict,
                          "declared": detail}
            # cut before wire: a verdict can carry both words, and retiring is
            # the decision that must not be softened into a rewiring proposal.
            action = ("cut" if ("cut" in verdict or "retire" in verdict)
                      else "wire" if ("wire" in verdict or "integrate" in verdict)
                      else "review")
            proposals.append({
                "id": "%s:%s" % (Path(name).stem, ident),
                "target": detail.get("target") or "unknown",
                "symbol": symbol,
                "nature": nature,
                "verdict": verdict,
                "proposed_action": action,
                "status": "proposed",
                "requires": "a patch; this file proposes, tools/self_modify.py decides",
                "evidence": detail,
            })
    # Stable order so a rerun diffs cleanly instead of reshuffling the queue.
    proposals.sort(key=lambda p: (p["proposed_action"], p["target"], p["symbol"]))
    return proposals


def main(argv: Sequence[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--summary", action="store_true", help="counts only, write nothing")
    ap.add_argument("--out", default=str(QUEUE.relative_to(ROOT)))
    ap.add_argument("--json", action="store_true")
    args = ap.parse_args(argv)

    rows = build()
    by_action = Counter(r["proposed_action"] for r in rows)
    by_nature = Counter(r["nature"] for r in rows)
    declared = _counts()
    derived = Counter(r["verdict"] for r in rows if r["verdict"] in declared)
    summary = {"proposals": len(rows),
               "by_action": dict(by_action),
               "by_nature": dict(by_nature.most_common(12)),
               "control_declared": declared,
               "control_derived": dict(derived),
               "control_match": bool(declared) and dict(derived) == declared,
               "generated": datetime.now(timezone.utc).isoformat()}

    if not args.summary:
        out = ROOT / args.out
        out.parent.mkdir(parents=True, exist_ok=True)
        with out.open("w", encoding="utf-8") as fh:
            for r in rows:
                fh.write(json.dumps(r, default=str) + "\n")
        summary["queue"] = args.out

    if args.json:
        print(json.dumps(summary, indent=2))
        return 0
    print("proposals: %d" % len(rows))
    for action, n in by_action.most_common():
        print("  %-8s %d" % (action, n))
    print("  top natures: %s" % dict(by_nature.most_common(6)))
    print("  control: declared=%s" % declared)
    print("           derived =%s" % dict(derived))
    if not args.summary:
        print("queue: %s" % args.out)
        print("work it with: python tools/self_modify.py --patch <patch>")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
