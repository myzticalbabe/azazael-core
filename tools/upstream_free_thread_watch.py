#!/usr/bin/env python
# coding: utf-8
"""Watch the upstream blocker behind the pmb/316t gap, and draft the filing.

WHY THIS EXISTS
The pmb daemon cannot run on a free-threaded interpreter, for TWO independent
reasons, and both live upstream -- neither can be fixed from inside this tree:

  * pywin32 has published NO free-threaded wheel for ANY version. Every wheel
    it has ever shipped carries a GIL ABI tag (cp39..cp315); not one carries
    a free-threaded one. The MCP Python SDK imports it at module level on
    Windows, so on a free-threaded interpreter ``import mcp`` fails before any
    application code runs.
  * the free-threaded WHEEL FRONTIER is one release behind this tree.
    Measured 2026-11-11: pydantic-core, torch, numpy and pillow ship
    cp313t/cp314t/cp315t; onnxruntime and tokenizers stop at cp314t; and NO
    package has a cp316t wheel at all. So the interpreter this tree runs
    (3.16t) is ahead of every wheel in the ecosystem.

The first is fixable without upstream help -- ``src/win32_shim`` rebuilds the
SDK's exact pywin32 surface on ctypes against kernel32, which needs no
compiled extension and therefore works on any interpreter. The second is not:
it is a property of the whole ecosystem and moves only when upstream ships
wheels.

WHY A WATCHER AND NOT A FILING
The MCP SDK's CONTRIBUTING.md is explicit: "The most useful contribution is a
good issue", PRs are reviewed only when a maintainer has assigned the linked
issue or it carries a `help wanted` label, and -- directly relevant here --
"If you have an agent filing PRs against open issues autonomously, please
turn it off for this repository", and "Keep a human in the loop ... Issues,
PRs, and comments generated by an agent without a person who has actually hit
the problem and read the output may be closed without warning."

So this tool does exactly what it is allowed to do: it READS the upstream
state, and it DRAFTS the filing for a human to post. It never writes to
upstream, it never authenticates, and it has no code path that could.

This tree's own precedent is `tools/interp_cycle.py watch`, which compares a
pinned upstream sha against CPython upstream and records the result under
`state/`. This is the same shape, for the same reason.

COMMANDS
  watch   read upstream (PyPI release metadata + the MCP SDK issue), record
          the finding under state/, and refresh the DRAFT filing. Read-only.
  draft   print the draft filing for a human to post. Posts nothing.
  verify  check that the local win32 shim is still conformant with the real
          pywin32 where pywin32 exists, and that the SDK imports with no
          pywin32 installed. Exits 2 when a check could not be performed.

USAGE
  python tools/upstream_free_thread_watch.py watch
  python tools/upstream_free_thread_watch.py draft
  python tools/upstream_free_thread_watch.py verify
"""
from __future__ import annotations

import argparse
import json
import os
import subprocess
import sys
import urllib.error
import urllib.request
from datetime import datetime, timezone
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
STATE = REPO_ROOT / "state"
REPORT = STATE / "upstream_free_thread.json"
DRAFT = STATE / "upstream_free_thread_draft.md"
SHIM = REPO_ROOT / "src" / "win32_shim"

PYPI = "https://pypi.org/pypi/%s/json"
MCP_ISSUE = ("https://api.github.com/repos/modelcontextprotocol/"
             "python-sdk/issues/2233")

#: The packages whose free-threaded wheels decide whether a free-threaded
#: interpreter can host the pmb stack at all. Chosen from the measured
#: dependency set, not from a guess.
PACKAGES = ("pydantic-core", "pydantic", "torch", "numpy", "onnxruntime",
            "tokenizers", "pillow", "pywin32")

#: The free-threaded ABI this tree targets. The frontier is measured against it.
TARGET_ABI = "cp316t"


def _now() -> str:
    return datetime.now(timezone.utc).isoformat(timespec="seconds")


def _get_json(url: str, timeout: int = 30):
    """GET JSON, or None. Never raises: an unreachable upstream is a reading."""
    req = urllib.request.Request(url, headers={
        "Accept": "application/vnd.github+json",
        "User-Agent": "azazael-upstream-free-thread-watch",
    })
    try:
        with urllib.request.urlopen(req, timeout=timeout) as resp:
            return json.loads(resp.read().decode("utf-8", "replace"))
    except Exception as exc:                     # noqa: BLE001 - a reading, not a crash
        return {"_error": "%s: %s" % (type(exc).__name__, exc)}


def _free_threaded_abis(pkg: str):
    """Every free-threaded ABI tag this package has published wheels for."""
    data = _get_json(PYPI % pkg)
    if not isinstance(data, dict) or "_error" in data:
        return None, data.get("_error", "unreachable") if isinstance(data, dict) else "unreachable"
    found = set()
    for files in (data.get("releases") or {}).values():
        for f in files:
            name = f.get("filename") or ""
            if not name.endswith(".whl"):
                continue
            parts = name.split("-")
            if len(parts) > 4 and parts[3].startswith("cp") and parts[3].endswith("t"):
                found.add(parts[3])
    return sorted(found), None


def _abi_rank(abi: str) -> int:
    digits = "".join(ch for ch in abi if ch.isdigit())
    return int(digits) if digits else 0


def survey() -> dict:
    """Measure the free-threaded frontier, package by package."""
    packages = {}
    frontier = 0
    for pkg in PACKAGES:
        abis, err = _free_threaded_abis(pkg)
        if err is not None:
            packages[pkg] = {"error": err}
            continue
        newest = max(abis, key=_abi_rank) if abis else None
        packages[pkg] = {
            "free_threaded_abis": abis,
            "newest": newest,
            "has_target_abi": TARGET_ABI in abis,
        }
        if newest:
            frontier = max(frontier, _abi_rank(newest))
    return {
        "measured_at": _now(),
        "target_abi": TARGET_ABI,
        "packages": packages,
        "frontier_abi": "cp%dt" % frontier if frontier else None,
        "packages_with_target_abi": sorted(
            p for p, v in packages.items() if v.get("has_target_abi")),
        "pywin32_has_any_free_threaded_wheel": bool(
            packages.get("pywin32", {}).get("free_threaded_abis")),
    }


def upstream_issue() -> dict:
    """The MCP SDK issue that tracks the pywin32 dependency."""
    data = _get_json(MCP_ISSUE)
    if not isinstance(data, dict) or "_error" in data:
        return {"error": data.get("_error", "unreachable") if isinstance(data, dict) else "unreachable"}
    return {
        "number": data.get("number"),
        "state": data.get("state"),
        "title": data.get("title"),
        "labels": [lb.get("name") for lb in (data.get("labels") or [])],
        "assignees": [a.get("login") for a in (data.get("assignees") or [])],
        "comments": data.get("comments"),
        # html_url is already absolute; prefixing it again produced
        # "https://github.com/https://github.com/...", which is not a link.
        "url": str(data.get("html_url", "")),
    }


def _draft_text(survey_report: dict, issue: dict) -> str:
    pkgs = survey_report.get("packages", {})
    lines = []
    lines.append("# Upstream filing draft -- NOT POSTED")
    lines.append("")
    lines.append("Prepared by `tools/upstream_free_thread_watch.py`. This file is a")
    lines.append("DRAFT for a human to review and post. Nothing here was sent: the")
    lines.append("watcher has no code path that writes to upstream, and the MCP SDK's")
    lines.append("CONTRIBUTING.md asks for a human in the loop on exactly this")
    lines.append("repository.")
    lines.append("")
    lines.append("## Suggested action")
    lines.append("")
    lines.append("Comment on the open issue (or a new issue) with the measured")
    lines.append("evidence below. Per CONTRIBUTING.md, an issue -- not a PR -- is")
    lines.append("the contribution that gets read; a PR is reviewed only after a")
    lines.append("maintainer assigns the linked issue or labels it `help wanted`.")
    lines.append("")
    if issue.get("number"):
        lines.append("Target issue: #%s (%s) -- %s" % (
            issue.get("number"), issue.get("state"), issue.get("url")))
        lines.append("")
    lines.append("## Measured evidence")
    lines.append("")
    lines.append("Free-threaded wheel availability per package, measured from the")
    lines.append("full published release history on PyPI:")
    lines.append("")
    lines.append("| package | free-threaded ABIs | has %s |" % TARGET_ABI)
    lines.append("|---|---|---|")
    for pkg in PACKAGES:
        info = pkgs.get(pkg, {})
        abis = info.get("free_threaded_abis")
        if abis is None:
            lines.append("| %s | (unreachable) | ? |" % pkg)
            continue
        lines.append("| %s | %s | %s |" % (
            pkg, ", ".join(abis) if abis else "NONE",
            "yes" if info.get("has_target_abi") else "no"))
    lines.append("")
    lines.append("Two independent consequences:")
    lines.append("")
    lines.append("1. **pywin32 has published no free-threaded wheel for any")
    lines.append("   version.** Every wheel it has ever shipped carries a GIL ABI")
    lines.append("   tag, so `pip install mcp` cannot resolve on a free-threaded")
    lines.append("   interpreter, and `import mcp` fails at module import because")
    lines.append("   `mcp/__init__.py` eagerly imports `mcp.client.stdio`.")
    lines.append("2. **The free-threaded wheel frontier is one release behind.**")
    lines.append("   The newest ABI with wheels anywhere in this dependency set is")
    lines.append("   `%s`, so a free-threaded interpreter one release newer cannot" %
                 (survey_report.get("frontier_abi") or "cp315t"))
    lines.append("   host the stack at all -- independently of pywin32.")
    lines.append("")
    lines.append("## A fix that needs no wheel")
    lines.append("")
    lines.append("The SDK's use of pywin32 is narrow and entirely Win32 API:")
    lines.append("Job Objects (so a stdio client's process tree dies with it) and")
    lines.append("one standard-handle fixup. Those are `kernel32` entry points, so")
    lines.append("they can be reached with `ctypes` -- no compiled extension, hence")
    lines.append("no ABI and no wheel. A reference implementation of exactly the")
    lines.append("SDK's surface lives at `src/win32_shim/` in this repository, and")
    lines.append("`tools/verify_win32_shim.py` compares it against the REAL")
    lines.append("pywin32 wherever pywin32 is installed.")
    lines.append("")
    lines.append("Two shape details matter if this is taken up, because they are")
    lines.append("where a naive implementation breaks:")
    lines.append("")
    lines.append("* `QueryInformationJobObject` must return a MUTABLE NESTED")
    lines.append("  DICT, not a ctypes struct. The SDK does")
    lines.append("  `info[\"BasicLimitInformation\"][\"LimitFlags\"] |= ...`, which")
    lines.append("  raises TypeError against a struct.")
    lines.append("* `STD_INPUT_HANDLE` / `STD_OUTPUT_HANDLE` / `STD_ERROR_HANDLE`")
    lines.append("  are the negative sentinels -10, -11 and -12 from `winnt.h`,")
    lines.append("  NOT the file descriptor numbers 0, 1 and 2.")
    lines.append("")
    lines.append("## Disclosure")
    lines.append("")
    lines.append("Prepared with AI assistance; every number above is measured by")
    lines.append("`tools/upstream_free_thread_watch.py` and reproducible with the")
    lines.append("commands it records. A human has reviewed this draft before")
    lines.append("posting.")
    lines.append("")
    lines.append("---")
    lines.append("")
    lines.append("Measured %s by `tools/upstream_free_thread_watch.py watch`."
                 % survey_report.get("measured_at"))
    return "\n".join(lines)


def cmd_watch(args) -> int:
    report = {"survey": survey(), "issue": upstream_issue()}
    STATE.mkdir(parents=True, exist_ok=True)
    REPORT.write_text(json.dumps(report, indent=2, sort_keys=True) + "\n",
                      encoding="utf-8")
    draft = _draft_text(report["survey"], report["issue"])
    DRAFT.write_text(draft + "\n", encoding="utf-8")
    print("wrote %s" % REPORT)
    print("wrote %s (DRAFT -- nothing posted)" % DRAFT)
    frontier = report["survey"].get("frontier_abi")
    print("frontier: %s | %s available: %s" % (
        frontier, TARGET_ABI,
        ", ".join(report["survey"].get("packages_with_target_abi") or []) or "none"))
    return 0


def cmd_draft(args) -> int:
    if not DRAFT.exists():
        print("no draft yet -- run: watch", file=sys.stderr)
        return 2
    print(DRAFT.read_text(encoding="utf-8"))
    return 0


def cmd_verify(args) -> int:
    """The local proofs: shim conformance, and the SDK importing with no pywin32.

    Run this with the interpreter the claim is about. The claim "the SDK
    imports with no pywin32" is TRUE on 3.15t (the newest free-threaded
    interpreter with wheels) and FALSE on 3.16t for an unrelated reason --
    pydantic 2.14 removed val_type_backport, which the SDK imports, and no
    pydantic-core cp316t wheel exists to fall back to. --interpreter selects
    the interpreter so the report says which one it measured.
    """
    interpreter = args.interpreter or sys.executable
    verifier = REPO_ROOT / "tools" / "verify_win32_shim.py"
    results = {"interpreter": interpreter}
    ok = True
    if verifier.exists():
        proc = subprocess.run([interpreter, str(verifier)],
                              capture_output=True, text=True,
                              encoding="utf-8", errors="replace", timeout=300)
        out = proc.stdout + proc.stderr
        results["shim_conformance"] = {
            "rc": proc.returncode,
            "conformant": "CONFORMANT" in out,
            "skipped": "real pywin32 not importable here" in out,
        }
        if proc.returncode != 0:
            ok = False
    else:
        results["shim_conformance"] = {"skipped": "verifier not present"}

    # The SDK must import with pywin32 BLOCKED.
    code = (
        "import sys, importlib.abc\n"
        "class Block(importlib.abc.MetaPathFinder):\n"
        "    def find_spec(self, name, path=None, target=None):\n"
        "        if name == 'pywin32' or name.startswith('pywin32.'):\n"
        "            raise ImportError('blocked')\n"
        "        return None\n"
        "sys.meta_path.insert(0, Block())\n"
        "sys.path.insert(0, %r)\n"
        "import mcp\n"
        "from mcp.os.win32 import utilities\n"
        "assert utilities.win32api is not None\n"
        "print('OK')\n" % str(SHIM)
    )
    proc = subprocess.run([interpreter, "-c", code], capture_output=True,
                          text=True, encoding="utf-8", errors="replace",
                          timeout=180)
    stderr = proc.stderr or ""
    # The failure, if any, may have NOTHING to do with pywin32. On this
    # tree's own 3.16t interpreter the SDK fails earlier and for a different
    # reason -- pydantic 2.14 removed val_type_backport, which the SDK
    # imports -- and on 3.15t it fails on pywin32. Attributing either to the
    # other would be exactly the kind of wrong-cause claim this tree's canon
    # forbids, so the blocker is NAMED from the traceback rather than guessed.
    if proc.returncode == 0:
        blocker = None
    elif "eval_type_backport" in stderr:
        blocker = "pydantic (eval_type_backport removed in pydantic 2.14)"
    elif "pywin32" in stderr or "win32api" in stderr or "win32job" in stderr:
        blocker = "pywin32"
    else:
        blocker = "unknown"
    results["sdk_imports_without_pywin32"] = {
        "rc": proc.returncode,
        "ok": "OK" in proc.stdout,
        "blocker": blocker,
        "error": stderr[-300:] if proc.returncode else "",
    }
    if proc.returncode != 0:
        ok = False
    print(json.dumps(results, indent=2, sort_keys=True))
    return 0 if ok else 1


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    sub = parser.add_subparsers(dest="cmd")
    sub.add_parser("watch", help="survey upstream and refresh the draft")
    sub.add_parser("draft", help="print the draft filing (posts nothing)")
    verify_p = sub.add_parser("verify", help="prove the local claims")
    verify_p.add_argument("--interpreter", default=None,
                          help="the interpreter to measure with (default: this one)")
    args = parser.parse_args(argv)
    if args.cmd == "watch":
        return cmd_watch(args)
    if args.cmd == "draft":
        return cmd_draft(args)
    if args.cmd == "verify":
        return cmd_verify(args)
    parser.print_help()
    return 2


if __name__ == "__main__":
    sys.exit(main())