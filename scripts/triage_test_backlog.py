#!/usr/bin/env python3
"""Triage the uncovered-module backlog (2026-09-12).

Input:  state/test_backlog.json  (written by repo_audit.py, import-graph based)
Output: state/test_backlog_triage.json

Every module gets exactly one verdict, so nothing is left in "unknown":

  vendor  third-party / vendored / generated code. Not ours to test.
  test    live code with no test reaching it. The work item.
  delete  no importer, no path-literal reference, no mention anywhere in the
          repo, not runnable - a dead-code CANDIDATE.

Conservative by construction. A static import graph cannot see dynamic
dispatch, and this repo loads modules by NAME at runtime (the worm registry's
``discover_worms()``), so "no importer" alone is not proof of death. A module
is only called `delete` when it is invisible by every cheap signal we have -
no import, no path literal, no string mention in any .py, no reference from a
.bat/.ps1/.sh/.yaml, and no ``__main__`` block. Deletion is deliberately NOT
performed here; the file lists candidates for review.

Usage:
    python scripts/triage_test_backlog.py
    python scripts/triage_test_backlog.py --show delete
"""
from __future__ import annotations

import argparse
import json
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BACKLOG = os.path.join(ROOT, "state", "test_backlog.json")
OUT = os.path.join(ROOT, "state", "test_backlog_triage.json")

# Vendored / generated markers. Checked against the path and the file header.
VENDOR_PATH_TOKENS = ("/vendor/", "/vendored/", "/third_party/", "/thirdparty/",
                      "/extern/", "/site-packages/", "/.venv", "/dist/",
                      "/build/", "/node_modules/")
VENDOR_HEADER = re.compile(
    r"(vendored|third[- ]party|do not edit|auto[- ]?generated|"
    r"generated by|this file is generated|@generated)",
    re.IGNORECASE)
HEADER_LINES = 25

# Config/script files that can invoke a module by name outside the import graph.
SCRIPT_EXTS = (".bat", ".cmd", ".ps1", ".sh", ".yaml", ".yml")
SCRIPT_SKIP = ("node_modules", ".git", "state/", "archive", "logs/", "backups/")


def _basename(rel: str) -> str:
    return os.path.basename(rel)[:-3]


def _script_blob() -> str:
    """Text of every launcher/config file, for name-based reference checks."""
    parts = []
    for dp, dn, fn in os.walk(ROOT):
        dn[:] = [d for d in dn if d not in (".git", "node_modules",
                                            "__pycache__", ".venv", ".venv-3.14t")]
        rel_dir = os.path.relpath(dp, ROOT).replace("\\", "/") + "/"
        if any(tok in rel_dir for tok in SCRIPT_SKIP):
            continue
        for f in fn:
            if f.endswith(SCRIPT_EXTS):
                try:
                    with open(os.path.join(dp, f), encoding="utf-8",
                              errors="replace") as fh:
                        parts.append(fh.read())
                except Exception:  # noqa: BLE001
                    pass
    return "\n".join(parts)


def _python_blob(imap) -> str:
    """Text of every .py file, for conservative name-mention checks."""
    parts = []
    for rel in sorted(imap.files):
        try:
            with open(os.path.join(ROOT, rel), encoding="utf-8",
                      errors="replace") as fh:
                parts.append(fh.read())
        except Exception:  # noqa: BLE001
            pass
    return "\n".join(parts)


def _is_vendored(rel: str) -> tuple[str, str]:
    """(kind, why) where kind is 'vendored' or 'generated', else ('', '').

    Both are "not ours to hand-test", but they are not the same thing: vendored
    is third-party, generated is this repo's own scaffolding. Calling the
    latter "vendored" would hide the fact that we own the generator.
    """
    low = "/" + rel.lower()
    for tok in VENDOR_PATH_TOKENS:
        if tok in low:
            return "vendored", "path contains %s" % tok
    try:
        with open(os.path.join(ROOT, rel), encoding="utf-8",
                  errors="replace") as f:
            header = "".join(next(f, "") for _ in range(HEADER_LINES))
    except Exception:  # noqa: BLE001
        return "", ""
    if re.search(r"author\s*:\s*auto-?generated", header, re.IGNORECASE):
        return "generated", "header marks it generated scaffolding"
    m = VENDOR_HEADER.search(header)
    if not m:
        return "", ""
    if "generated" in m.group(0).lower():
        return "generated", "header: '%s'" % m.group(0)
    return "vendored", "header: '%s'" % m.group(0)


def triage(show_all: bool = False) -> dict:
    import import_map

    if not os.path.exists(BACKLOG):
        raise SystemExit("no %s - run scripts/repo_audit.py first" % BACKLOG)
    with open(BACKLOG, encoding="utf-8") as f:
        backlog = json.load(f)
    uncovered = backlog.get("uncovered") or []

    imap = import_map.get_map()
    py_blob = _python_blob(imap)
    script_blob = _script_blob()

    rows = []
    for rel in uncovered:
        base = _basename(rel)
        kind, why = _is_vendored(rel)
        if kind:
            importers = sorted(imap.importers(rel))
            evidence = why
            if importers:
                # Generated but imported is still live code the suite ignores.
                evidence += " (live: imported by %d)" % len(importers)
            rows.append({"module": base, "path": rel, "verdict": "vendor",
                         "kind": kind, "live": bool(importers),
                         "evidence": evidence})
            continue

        importers = sorted(imap.importers(rel))
        refs = sorted(imap.referenced_by(rel))
        mentioned = bool(re.search(r"\b%s\b" % re.escape(base), py_blob))
        in_script = base in script_blob
        runnable = rel in imap.has_main

        if importers:
            rows.append({"module": base, "path": rel, "verdict": "test",
                         "evidence": "imported by %d module(s): %s"
                                     % (len(importers), ", ".join(importers[:3]))})
        elif refs:
            rows.append({"module": base, "path": rel, "verdict": "test",
                         "evidence": "named by %d file(s): %s"
                                     % (len(refs), ", ".join(refs[:3]))})
        elif in_script:
            rows.append({"module": base, "path": rel, "verdict": "test",
                         "evidence": "named in a launcher/config file"})
        elif runnable:
            rows.append({"module": base, "path": rel, "verdict": "test",
                         "evidence": "has a __main__ block (runnable)"})
        elif mentioned:
            rows.append({"module": base, "path": rel, "verdict": "test",
                         "evidence": "name mentioned in .py text only "
                                     "(possible dynamic use)"})
        else:
            rows.append({"module": base, "path": rel, "verdict": "delete",
                         "evidence": "no import, reference, mention or "
                                     "__main__ - dead-code candidate",
                         "requires_review": True})

    counts = {"test": 0, "delete": 0, "vendor": 0}
    for r in rows:
        counts[r["verdict"]] += 1
    unknown = [r for r in rows if r["verdict"] not in counts]
    vendor_kind = {
        "vendored": sum(1 for r in rows if r.get("kind") == "vendored"),
        "generated": sum(1 for r in rows if r.get("kind") == "generated"),
        "generated_and_live": sum(1 for r in rows
                                  if r.get("kind") == "generated" and r.get("live")),
    }

    out = {
        "at": backlog.get("at"),
        "source": os.path.relpath(BACKLOG, ROOT).replace("\\", "/"),
        "method": backlog.get("method"),
        "total": len(rows),
        "counts": counts,
        "vendor_kind": vendor_kind,
        "unknown_count": len(unknown),
        "delete_candidates": [r["path"] for r in rows
                              if r["verdict"] == "delete"],
        "rows": rows,
    }
    with open(OUT + ".tmp", "w", encoding="utf-8") as f:
        json.dump(out, f, indent=2)
    os.replace(OUT + ".tmp", OUT)

    print("triaged %d uncovered modules -> %s" % (len(rows), OUT))
    print("  test   %d  (live, no test reaches it)" % counts["test"])
    print("  vendor %d  (vendored %d, generated %d, of which live %d)"
          % (counts["vendor"], vendor_kind["vendored"],
             vendor_kind["generated"], vendor_kind["generated_and_live"]))
    print("  delete %d  (dead-code candidates, review before removal)"
          % counts["delete"])
    print("  unknown %d" % len(unknown))

    if show_all or len(rows) <= 40:
        for r in rows:
            print("    [%-6s] %-58s %s" % (r["verdict"], r["path"],
                                           r["evidence"][:70]))
    return out


def main() -> int:
    ap = argparse.ArgumentParser(description="Triage the test backlog")
    ap.add_argument("--show", choices=["test", "delete", "vendor", "all"],
                    default=None, help="print rows of one verdict")
    args = ap.parse_args()
    result = triage(show_all=(args.show == "all"))
    if args.show and args.show != "all":
        for r in result["rows"]:
            if r["verdict"] == args.show:
                print("    [%-6s] %-58s %s" % (r["verdict"], r["path"],
                                               r["evidence"][:70]))
    return 0 if result["unknown_count"] == 0 else 1


if __name__ == "__main__":
    sys.exit(main())
