DOMAINS = ("O", "C", "E", "A", "N", "H")
PULL_WEIGHT = 0.55  # situation pull vs temperament baseline in responses
# Openness channel (identifiability, literature-grounded): openness predicts
# responsiveness to novelty and aesthetic situations (aesthetic-chills
# literature). Without it, O is structurally invisible to affect-forward
# identification (measured r ~ 0.0): nothing in PAD displacement varies
# with O. So the effective pull weight grows with unexpectedness for
# high-O persons and shrinks for low-O ones. Editable constant, tested
# by the recovery gate.
OPENNESS_NOVELTY_GAIN = 1.0


def situation_pull(situation: dict) -> tuple[float, float, float]:
    """PAD pull of one battery situation (person-independent)."""
    kind = situation.get("kind")
    if kind == "action":
        out = A.appraise_action(situation.get("praiseworthiness", 0.0),
                                self_agent=situation.get("self_agent", True),
                                effort=situation.get("effort", 0.0))
    elif kind == "object":
        out = A.appraise_object(situation.get("appealingness", 0.0),
                                familiarity=situation.get("familiarity", 0.5))
    else:
        out = A.appraise_event(situation.get("desirability", 0.0),
                               likelihood=situation.get("likelihood", 1.0),
                               confirmed=situation.get("confirmed"),
                               effort=situation.get("effort", 0.0),
                               unexpectedness=situation.get("unexpectedness", 0.0),
                               for_other=situation.get("for_other", False),
                               liking_other=situation.get("liking_other", 0.0))
    if not out:
        return (0.0, 0.0, 0.0)
    fam, intensity, _basis = out[0]
    return A.emotion_to_pad(fam, intensity)


def predict_pad(theta: dict, situation: dict,
                weights: dict | None = None) -> tuple[float, float, float]:
    """Forward model: blend of temperament baseline and situation pull."""
    base = A.temperament(theta, weights)
    pull = situation_pull(situation)
    o_centered = (float(theta.get("O", 3.0)) - 3.0) / 2.0
    novelty = max(0.0, min(1.0, float(situation.get("unexpectedness", 0.0))))
    w_eff = PULL_WEIGHT * (1.0 + OPENNESS_NOVELTY_GAIN * o_centered * novelty)
    w_eff = max(0.05, min(0.95, w_eff))
    return A.pad_blend(base, pull, w_eff)


def simulate_responses(theta: dict, situations=SITUATION_BATTERY,
                       noise: float = 0.05, seed: int = 7,
                       weights: dict | None = None) -> list:
    """Synthetic person: forward model + Gaussian response noise."""
    rng = random.Random(seed)
    out = []
    for sit in situations:
        pad = predict_pad(theta, sit, weights)
        out.append(A.pad_normalize(
            tuple(v + rng.gauss(0.0, noise) for v in pad)))
    return out


def _mse(theta: dict, responses: list, situations,
         weights, l2: float) -> float:
    err, n = 0.0, 0
    for pad, sit in zip(responses, situations):
        pred = predict_pad(theta, sit, weights)
        err += sum((a - b) ** 2 for a, b in zip(pad, pred))
        n += 1
    prior = sum((float(theta.get(d, 3.0)) - 3.0) ** 2 for d in DOMAINS)
    return err / max(1, n) + l2 * prior


def fit_traits(responses: list, situations=SITUATION_BATTERY,
               weights: dict | None = None, l2: float = 0.02,
               steps: tuple = (0.5, 0.25, 0.1, 0.05)) -> dict:
    """Regularized coordinate descent over 1..5 per domain.

    Returns {"theta": {...}, "mse": ..., "prior_mse": ..., "n_iter": ...}.
    prior_mse (all-neutral theta) is reported so the gate can assert the
    fit actually beats doing nothing.
    """
    theta = {d: 3.0 for d in DOMAINS}
    prior_mse = _mse(theta, responses, situations, weights, 0.0)
    n_iter = 0
    for step in steps:
        for _ in range(40):
            improved = False
            for d in DOMAINS:
                cur = _mse(theta, responses, situations, weights, l2)
                best, best_v = theta[d], cur
                for cand in (theta[d] - step, theta[d] + step):
                    if not 1.0 <= cand <= 5.0:
                        continue
                    theta[d] = round(cand, 3)
                    v = _mse(theta, responses, situations, weights, l2)
                    if v < best_v - 1e-12:
                        best, best_v = theta[d], v
                        improved = True
                theta[d] = best
                n_iter += 1
            if not improved:
                break
    return {"theta": dict(theta),
            "mse": round(_mse(theta, responses, situations, weights, 0.0), 5),
            "prior_mse": round(prior_mse, 5),
            "n_iter": n_iter}


def pearson(xs: list[float], ys: list[float]) -> float:
    """Pearson r, stdlib (no numpy dependency for a 6-line formula)."""
    n = len(xs)
    mx, my = sum(xs) / n, sum(ys) / n
    cov = sum((x - mx) * (y - my) for x, y in zip(xs, ys))
    vx = sum((x - mx) ** 2 for x in xs)
    vy = sum((y - my) ** 2 for y in ys)
    if vx <= 0 or vy <= 0:
        return 0.0
    return max(-1.0, min(1.0, cov / math.sqrt(vx * vy)))


def recovery_report(true_thetas: list[dict], fitted: list[dict]) -> dict:
    """Per-domain Pearson r of fitted vs true across synthetic persons."""
    out = {}
    for d in DOMAINS:
        xs = [float(t[d]) for t in true_thetas]
        ys = [float(f["theta"][d]) for f in fitted]
        out[d] = round(pearson(xs, ys), 3)
    return out
