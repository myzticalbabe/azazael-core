"""PSYCHE Phase 2 — identification: behavior in, traits out (H3).

The PAD battery inverts the temperament map. Forward model (generative,
per person): for each scripted situation, appraisal yields an emotion pull
in PAD space; the observed response is a blend of the person's temperament
baseline and that pull. Fitting inverts it: find the theta whose baseline
best explains the observed responses, regularized toward neutral.

HONEST SCOPE, read before extending: this proves IDENTIFIABILITY under the
model (synthetic persons generated by the forward model are recovered by
the inverse), not validity against humans. Human validity is Phase 5's
eval harness. A recovery test that used a different generator than the
fitter would test nothing; a recovery test at all is what H3 demands:
if theta cannot be recovered even here, the artifact's core claim fails
in the cheapest possible setting.

Why coordinate descent, not closed form: the forward map (blend of
baseline with per-situation pulls, all clamped) is piecewise-nonlinear,
and domains are bounded 1..5. Descent with shrinking steps is exact
enough, dependency-free, and auditable step by step.

Regularization toward 3.0 (neutral) is load-bearing, not a fudge: 18
situations underdetermine 6 domains, so without a prior the fit chases
noise. The prior says "an unmeasured person is average" -- the only
defensible default, and the gate pins that neutral responses stay neutral.
"""
