# ── Data Types ───────────────────────────────────────────────────────

@dataclass
class Alert:
    """An alert generated by threshold evaluation."""
    level: str = "info"  # "info", "warning", "critical"
    metric: str = ""
    message: str = ""
    value: float = 0.0
    threshold: float = 0.0


@dataclass
class SystemSnapshot:
    """A point-in-time capture of system resource usage."""
    timestamp: str = field(default_factory=lambda: datetime.now().isoformat())
    cpu_percent: float = 0.0
    cpu_count: int = 1
    memory_total_gb: float = 0.0
    memory_used_gb: float = 0.0
    memory_percent: float = 0.0
    swap_used_gb: float = 0.0
    disk_used_percent: float = 0.0
    disk_free_gb: float = 0.0
    io_read_mb: float = 0.0
    io_write_mb: float = 0.0
    network_sent_mb: float = 0.0
    network_recv_mb: float = 0.0
    process_count: int = 0


@dataclass
class ProcessSnapshot:
    """Resource usage of a specific process."""
    pid: int = 0
    name: str = ""
    cpu_percent: float = 0.0
    memory_rss_mb: float = 0.0
    memory_vms_mb: float = 0.0
    threads: int = 0
    open_files: int = 0
    uptime_seconds: float = 0.0


@dataclass
class DBHealthSnapshot:
    """Health of a SQLite database."""
    path: str = ""
    size_mb: float = 0.0
    wal_size_mb: float = 0.0
    integrity: str = "unknown"
    page_count: int = 0
    freelist_count: int = 0
    schema_version: str = "unknown"


@dataclass
class ServiceHealth:
    """Health check result for a service endpoint."""
    name: str = ""
    url: str = ""
    reachable: bool = False
    status_code: int = 0
    latency_ms: float = 0.0
    version: str = ""
    error: str = ""


# ── Main Monitor ─────────────────────────────────────────────────────

class PerformanceMonitor:
    """Centralized performance monitoring across all projects.

    Usage:
        pm = PerformanceMonitor()
        snap = pm.capture()          # Full system + process + DB + service snapshot
        pm.print_snapshot(snap)      # Human-readable
        pm.save_snapshot(snap, "snapshots/snap_001.json")  # Persist
    """

    # Default services to health-check
    DEFAULT_SERVICES = [
        ("ollama", "http://localhost:11434/"),
        ("llama-server", "http://localhost:8080/health"),
        ("openmono-rust", "http://localhost:9090/health"),
        ("openmono-go", "http://localhost:9091/health"),
    ]

    # Default DBs to monitor
    DEFAULT_DBS = [
        "workspace/session_memory.db",
        "workspace/graph.db",
    ]

    # Processes of interest (name keywords)
    WATCHED_PROCESSES = [
        "python", "ollama", "llama-server", "openmono", "go-bridge",
        "rust-bindings", "node", "docker",
    ]

    def __init__(self, db_paths: (list[str] | None) = None,
                 services: (list[tuple[str, str]] | None) = None):
        self.db_paths = db_paths or self.DEFAULT_DBS
        self.services = services or self.DEFAULT_SERVICES

    # ── System Metrics ──────────────────────────────────────────

    def capture_system(self) -> SystemSnapshot:
        """Capture system-level resource metrics."""
        snap = SystemSnapshot()

        if not HAS_PSUTIL:
            return snap

        if psutil is None:  # unreachable: HAS_PSUTIL mirrors this flag above
            raise RuntimeError("psutil is not installed")

        try:
            snap.cpu_percent = psutil.cpu_percent(interval=0.1)
            snap.cpu_count = psutil.cpu_count() or 1
            mem = psutil.virtual_memory()
            snap.memory_total_gb = round(mem.total / (1024 ** 3), 2)
            snap.memory_used_gb = round(mem.used / (1024 ** 3), 2)
            snap.memory_percent = mem.percent
            swap = psutil.swap_memory()
            snap.swap_used_gb = round(swap.used / (1024 ** 3), 2)
            disk = psutil.disk_usage("/")
            snap.disk_used_percent = disk.percent
            snap.disk_free_gb = round(disk.free / (1024 ** 3), 2)

            io_counters = psutil.disk_io_counters()
            if io_counters:
                snap.io_read_mb = round(io_counters.read_bytes / (1024 ** 2), 2)
                snap.io_write_mb = round(io_counters.write_bytes / (1024 ** 2), 2)

            net_io = psutil.net_io_counters()
            if net_io:
                snap.network_sent_mb = round(net_io.bytes_sent / (1024 ** 2), 2)
                snap.network_recv_mb = round(net_io.bytes_recv / (1024 ** 2), 2)

            snap.process_count = len(psutil.pids())
        except Exception as exc:
            note_failure("performance_monitor:L200", exc) # Graceful degradation  # scanner:ignore

        return snap

    # ── Process Metrics ─────────────────────────────────────────

    #: `open_files` is the single most expensive attribute psutil exposes on
    #: Windows: answering it makes psutil build the ENTIRE system handle table,
    #: and `process_iter(attrs=[...])` asks for it once PER PROCESS -- so the
    #: original loop cost O(processes x handles). Measured on this host
    #: 2026-09-28: 10.5 s for 277 processes while idle, >40 s under load. That
    #: is what blew the 600 s chunk-4 suite budget, via
    #: `SessionMemory.end_session` -> `get_perf_delta` -> `capture`.
    INCLUDE_OPEN_FILES = True
    #: Ceiling for ONE `open_files` probe.
    OPEN_FILES_DEADLINE_S = 2.0
    #: Ceiling for ALL `open_files` probes in one capture, so a pathological
    #: handle table cannot multiply by the number of watched processes.
    OPEN_FILES_BUDGET_S = 3.0

    def _open_files_count(self, proc: Any, timeout: float) -> int:
        """Count a process's open files without ever blocking the caller."""
        box: dict[str, int] = {}

        def _work() -> None:
            try:
                box["n"] = len(proc.open_files() or [])
            except Exception as exc:           # noqa: BLE001 - best effort metric
                note_failure("performance_monitor:L228", exc)
                box["n"] = 0

        worker = threading.Thread(target=_work, daemon=True)
        worker.start()
        worker.join(timeout)
        return box.get("n", 0)

    def capture_watched_processes(self,
                                  include_open_files: bool | None = None
                                  ) -> list[ProcessSnapshot]:
        """Capture resource usage for all watched processes."""
        if not HAS_PSUTIL:
            return []

        if psutil is None:  # unreachable: HAS_PSUTIL mirrors this flag above
            raise RuntimeError("psutil is not installed")

        want_files = (self.INCLUDE_OPEN_FILES
                      if include_open_files is None else include_open_files)

        # Pass 1 (cheap): pid + name only. Filter on those BEFORE touching the
        # expensive attributes, which was the O(processes x handles) bug.
        candidates: list[tuple[int, str]] = []
        try:
            for proc in psutil.process_iter(["pid", "name"]):
                try:
                    info = proc.info
                    name = info["name"] or ""
                    if not any(kw.lower() in name.lower()
                               for kw in self.WATCHED_PROCESSES):
                        continue
                    candidates.append((info["pid"] or 0, name))
                except (psutil.NoSuchProcess, psutil.AccessDenied) as exc:
                    note_failure("performance_monitor:L258", exc)
                    continue
        except Exception as exc:
            note_failure("performance_monitor:L260", exc) # scanner:ignore

        # Pass 2: only the matched processes pay for the expensive attributes.
        snapshots = []
        files_budget_end = time.perf_counter() + self.OPEN_FILES_BUDGET_S
        for pid, name in candidates:
            try:
                proc = psutil.Process(pid)
                with proc.oneshot():
                    mem = proc.memory_info()
                    cpu = proc.cpu_percent()
                    threads = proc.num_threads()
                    created = proc.create_time()

                open_files = 0
                if want_files:
                    remaining = files_budget_end - time.perf_counter()
                    if remaining > 0.02:
                        open_files = self._open_files_count(
                            proc, min(self.OPEN_FILES_DEADLINE_S, remaining))

                snapshots.append(ProcessSnapshot(
                    pid=pid,
                    name=name,
                    cpu_percent=cpu or 0.0,
                    memory_rss_mb=round((mem.rss if mem else 0) / (1024 ** 2), 2),
                    memory_vms_mb=round((mem.vms if mem else 0) / (1024 ** 2), 2),
                    threads=threads or 0,
                    open_files=open_files,
                    uptime_seconds=round(time.time() - (created or time.time()), 0),
                ))
            except (psutil.NoSuchProcess, psutil.AccessDenied) as exc:
                note_failure("performance_monitor:L292", exc)
                continue
            except Exception as exc:
                note_failure("performance_monitor:L294", exc)
                continue

        return sorted(snapshots, key=lambda s: s.memory_rss_mb, reverse=True)

    # ── Database Health ─────────────────────────────────────────

    def capture_db_health(self) -> list[DBHealthSnapshot]:
        """Check health of all monitored SQLite databases."""
        if not HAS_SQLITE:
            return []

        snapshots = []
        for db_path in self.db_paths:
            path = Path(db_path)
            if not path.exists():
                continue

            try:
                conn = _sqlite.connect(str(path))
                try:
                    size_mb = path.stat().st_size / (1024 ** 2)

                    wal_path = Path(str(path) + "-wal")
                    wal_size_mb = (wal_path.stat().st_size / (1024 ** 2)
                                   if wal_path.exists() else 0.0)

                    integrity = conn.execute("PRAGMA integrity_check").fetchone()
                    page_count = conn.execute("PRAGMA page_count").fetchone()
                    freelist = conn.execute("PRAGMA freelist_count").fetchone()
                    # Not all DBs have a metadata table — fall back gracefully
                    try:
                        schema_ver = conn.execute(
                            "SELECT value FROM metadata WHERE key='schema_version'"
                        ).fetchone()
                    except Exception as exc:
                        note_failure("performance_monitor:L329", exc)
                        schema_ver = None

                    snap = DBHealthSnapshot(
                        path=str(path),
                        size_mb=round(size_mb, 2),
                        wal_size_mb=round(wal_size_mb, 2),
                        integrity=str(integrity[0]) if integrity else "unknown",
                        page_count=page_count[0] if page_count else 0,
                        freelist_count=freelist[0] if freelist else 0,
                        schema_version=schema_ver[0] if schema_ver else "unknown",
                    )
                    snapshots.append(snap)
                finally:
                    conn.close()
            except Exception as exc:
                note_failure("performance_monitor:L344", exc) # scanner:ignore

        return snapshots

    # ── Service Health ──────────────────────────────────────────

    #: Per-service CONNECT timeout. A single float bounds connect AND read, but
    #: a dead localhost port still cost ~4 s (an IPv6 attempt, then IPv4), and
    #: the whole capture ran synchronously inside `SessionMemory.start_session`.
    #: Splitting them lets a dead port fail fast while a live-but-slow service
    #: (ollama takes ~2 s to answer `/`) is still detected.
    #: Tuned for the DEFAULT_SERVICES, which are all localhost: a live listener
    #: completes the TCP handshake from its backlog even if the application is
    #: slow to answer, so only a dead port ever burns this. Raise it if
    #: `services` is pointed at a remote host.
    SERVICE_CONNECT_TIMEOUT_S = 0.3
    SERVICE_READ_TIMEOUT_S = 5.0
    #: HARD ceiling for ONE probe, enforced with a daemon thread. `timeout=`
    #: does NOT bound `socket.getaddrinfo`, so a slow or wedged resolver blocks
    #: the caller forever whatever timeout is passed. Measured 2026-09-28:
    #: `SessionMemory.start_session` blocked >25 s standalone and >150 s (the
    #: whole chunk-4 suite budget) inside `urllib3 ... create_connection`.
    SERVICE_PROBE_DEADLINE_S = 8.0
    #: Probes run in PARALLEL, so the whole set is bounded by this single
    #: ceiling instead of by (number of services x ceiling).

    def _probe_service(self, name: str, url: str,
                       deadline: float) -> ServiceHealth:
        """One service probe with a hard deadline; never waits forever."""
        box: dict[str, Any] = {}

        def _work() -> None:
            try:
                if _requests is None:  # unreachable: HAS_REQUESTS gates every probe
                    raise RuntimeError("requests is not installed")
                start = time.perf_counter()
                resp = _requests.get(url, timeout=(
                    self.SERVICE_CONNECT_TIMEOUT_S,
                    self.SERVICE_READ_TIMEOUT_S,
                ))
                box["latency_ms"] = (time.perf_counter() - start) * 1000
                box["resp"] = resp
            except Exception as exc:        # noqa: BLE001 - reported, not raised
                note_failure("performance_monitor:L385", exc)
                box["error"] = str(exc)[:200]

        worker = threading.Thread(target=_work, daemon=True)
        worker.start()
        worker.join(deadline)
        if worker.is_alive():
            return ServiceHealth(
                name=name, url=url, reachable=False,
                error=("probe exceeded %.1fs deadline "
                       "(unbounded DNS/connect)" % deadline),
            )
        if "error" in box:
            return ServiceHealth(name=name, url=url, reachable=False,
                                 error=box["error"])
        resp = box.get("resp")
        if resp is None:  # unreachable: _work stores "error" unless it stored resp
            raise RuntimeError("service probe recorded no response object")
        version = ""
        try:
            body = resp.json()
            if isinstance(body, dict):
                version = body.get("version", "")
        except Exception as exc:
            note_failure("performance_monitor:L406", exc) # scanner:ignore
        return ServiceHealth(
            name=name, url=url, reachable=True,
            status_code=resp.status_code,
            latency_ms=round(box.get("latency_ms", 0.0), 1),
            version=version,
        )

    def capture_service_health(self) -> list[ServiceHealth]:
        """Health-check all monitored services, within a bounded budget."""
        if not HAS_REQUESTS:
            return [ServiceHealth(
                name=name, url=url, reachable=False,
                error="requests not installed"
            ) for name, url in self.services]

        if not self.services:
            return []

        # Probes are independent, so run them concurrently: three dead
        # localhost ports cost ~1.8 s EACH when probed serially (5.3 s for the
        # default set, measured 2026-09-28), and this runs on every
        # `SessionMemory.start_session`.
        results: list[ServiceHealth | None] = [None] * len(self.services)

        def _one(idx: int, name: str, url: str) -> None:
            results[idx] = self._probe_service(
                name, url, self.SERVICE_PROBE_DEADLINE_S)

        workers = [threading.Thread(target=_one, args=(i, n, u), daemon=True)
                   for i, (n, u) in enumerate(self.services)]
        for w in workers:
            w.start()
        for w in workers:
            w.join(self.SERVICE_PROBE_DEADLINE_S + 0.5)

        out = []
        for res, (name, url) in zip(results, self.services):
            if res is None:
                res = ServiceHealth(
                    name=name, url=url, reachable=False,
                    error=("probe did not complete within %.1fs"
                           % self.SERVICE_PROBE_DEADLINE_S))
            out.append(res)
        return out

    # ── Alerting Thresholds ────────────────────────────────────

    CPU_CRITICAL = 90.0
    MEMORY_WARNING = 80.0
    MEMORY_CRITICAL = 90.0
    DB_SIZE_WARNING_MB = 100.0

    def evaluate_alerts(self, snapshot: dict[str, Any]) -> list[Alert]:
        """Evaluate thresholds against a snapshot and return triggered alerts."""
        alerts = []
        sys_info = snapshot.get("system", {})
        dbs = snapshot.get("databases", [])

        # CPU
        cpu = sys_info.get("cpu_percent", 0)
        if cpu >= self.CPU_CRITICAL:
            alerts.append(Alert(
                level="critical", metric="cpu_percent",
                message=f"CPU at {cpu:.1f}% — exceeds critical threshold of {self.CPU_CRITICAL}%",
                value=cpu, threshold=self.CPU_CRITICAL,
            ))

        # Memory
        mem = sys_info.get("memory_percent", 0)
        if mem >= self.MEMORY_CRITICAL:
            alerts.append(Alert(
                level="critical", metric="memory_percent",
                message=f"Memory at {mem:.1f}% — exceeds critical threshold of {self.MEMORY_CRITICAL}%",
                value=mem, threshold=self.MEMORY_CRITICAL,
            ))
        elif mem >= self.MEMORY_WARNING:
            alerts.append(Alert(
                level="warning", metric="memory_percent",
                message=f"Memory at {mem:.1f}% — exceeds warning threshold of {self.MEMORY_WARNING}%",
                value=mem, threshold=self.MEMORY_WARNING,
            ))

        # Database sizes
        for d in dbs:
            size = d.get("size_mb", 0)
            if size >= self.DB_SIZE_WARNING_MB:
                alerts.append(Alert(
                    level="warning", metric="db_size",
                    message=f"Database {d.get('path', '?')} at {size:.1f} MB exceeds {self.DB_SIZE_WARNING_MB} MB warning threshold",
                    value=size, threshold=self.DB_SIZE_WARNING_MB,
                ))

        return alerts

    # ── Full Capture ────────────────────────────────────────────

    def capture(self) -> dict[str, Any]:
        """Full capture: system + processes + DBs + services + alerts."""
        snapshot = {
            "captured_at": datetime.now().isoformat(),
            "system": self._snapshot_to_dict(self.capture_system()),
            "processes": [self._snapshot_to_dict(p)
                         for p in self.capture_watched_processes()],
            "databases": [self._snapshot_to_dict(d)
                         for d in self.capture_db_health()],
            "services": [self._snapshot_to_dict(s)
                        for s in self.capture_service_health()],
        }
        snapshot["alerts"] = [self._snapshot_to_dict(a)
                              for a in self.evaluate_alerts(snapshot)]
        return snapshot

    # ── Formatting ──────────────────────────────────────────────

    def format_summary(self, snapshot: dict[str, Any]) -> str:
        """Format a capture snapshot as a human-readable summary."""
        sys_info = snapshot.get("system", {})
        procs = snapshot.get("processes", [])
        dbs = snapshot.get("databases", [])
        svcs = snapshot.get("services", [])

        lines = []
        lines.append("=" * 60)
        lines.append(f"  PERFORMANCE SNAPSHOT — {snapshot.get('captured_at', '?')}")
        lines.append("=" * 60)

        if sys_info:
            lines.append("\n  System:")
            lines.append(f"    CPU: {sys_info.get('cpu_percent', 0):.1f}% "
                        f"({sys_info.get('cpu_count', 1)} cores)")
            lines.append(f"    Memory: {sys_info.get('memory_used_gb', 0):.1f} / "
                        f"{sys_info.get('memory_total_gb', 0):.1f} GB "
                        f"({sys_info.get('memory_percent', 0):.1f}%)")
            lines.append(f"    Disk: {sys_info.get('disk_used_percent', 0):.1f}% used, "
                        f"{sys_info.get('disk_free_gb', 0):.1f} GB free")
            lines.append(f"    Processes: {sys_info.get('process_count', 0)}")

        if procs:
            lines.append(f"\n  Watched Processes ({len(procs)}):")
            for p in procs[:8]:
                lines.append(
                    f"    {p['name']:20s}  PID {p['pid']:>6d}  "
                    f"CPU {p.get('cpu_percent', 0):5.1f}%  "
                    f"RSS {p.get('memory_rss_mb', 0):7.1f} MB  "
                    f"{p.get('threads', 0)} threads"
                )

        if dbs:
            lines.append(f"\n  Databases ({len(dbs)}):")
            for d in dbs:
                status = "✓" if d.get("integrity") == "ok" else "✗"
                lines.append(
                    f"    {status} {d['path']:40s}  "
                    f"{d.get('size_mb', 0):5.1f} MB  "
                    f"WAL {d.get('wal_size_mb', 0):5.1f} MB"
                )

        if svcs:
            lines.append(f"\n  Services ({len(svcs)}):")
            for s in svcs:
                if s.get("reachable"):
                    lines.append(
                        f"    ✓ {s['name']:20s}  "
                        f"{s.get('latency_ms', 0):5.1f} ms  "
                        f"v{s.get('version', '?')}"
                    )
                else:
                    lines.append(
                        f"    ✗ {s['name']:20s}  "
                        f"unreachable: {s.get('error', '?')[:40]}"
                    )

        lines.append("\n" + "=" * 60)
        return "\n".join(lines)

    def print_snapshot(self, snapshot: (dict[str, Any] | None) = None):
        """Capture (if needed) and print a snapshot."""
        if snapshot is None:
            snapshot = self.capture()
        print(self.format_summary(snapshot))

    # ── Persistence ─────────────────────────────────────────────

    def save_snapshot(self, snapshot: dict[str, Any], filepath: str):
        """Save a snapshot to a JSON file."""
        path = Path(filepath)
        path.parent.mkdir(parents=True, exist_ok=True)
        with open(path, "w", encoding="utf-8") as f:  # scanner:ignore
            json.dump(snapshot, f, indent=2)

    def load_snapshot(self, filepath: str) -> dict[str, Any]:
        """Load a snapshot from a JSON file."""
        with open(filepath, encoding="utf-8") as f:  # scanner:ignore
            return json.load(f)

    # ── Helpers ─────────────────────────────────────────────────

    @staticmethod
    def _snapshot_to_dict(obj: Any) -> dict[str, Any]:
        """Convert a dataclass to a dict."""
        if hasattr(obj, "__dataclass_fields__"):
            return {k: getattr(obj, k) for k in obj.__dataclass_fields__}
        return obj


# ── Convenience ───────────────────────────────────────────────────────

def quick_snapshot() -> dict[str, Any]:
    """One-shot: capture and return a full performance snapshot."""
    return PerformanceMonitor().capture()


def quick_print():
    """One-shot: capture and print a performance snapshot."""
    PerformanceMonitor().print_snapshot()


