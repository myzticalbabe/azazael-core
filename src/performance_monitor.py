"""
PerformanceMonitor — Cross-Project System Monitoring
=====================================================
Centralized performance monitoring for all AZAZAEL projects.

Aggregates metrics from multiple sources:
- psutil-based CPU, memory, disk, I/O stats
- Process-level resource tracking (RSS, CPU%, threads)
- WAL/journal monitoring for SQLite DBs
- HTTP endpoint health checks (Ollama, llama-server, openmono)
- Goroutine/thread pool monitoring
- Graceful degradation when optional dependencies are missing

Previously, performance monitoring was scattered across 6+ subsystems:
  - azazael_wsa.py (per-subsystem psutil snapshots)
  - HYDRA_CLUSTER Phase 6 / FEEDBACK
  - WORMZ_EXECUTION I/O monitoring
  - openmono.ai/scripts/perf_logs/ echo*.perf_log
  - llama-server --metrics flag
  - Docker compose health checks

This module unifies them all into a single monitoring interface.

Usage:
    >>> from performance_monitor import PerformanceMonitor
    >>> pm = PerformanceMonitor()
    >>> snapshot = pm.capture()
    >>> print(pm.format_summary(snapshot))
"""

