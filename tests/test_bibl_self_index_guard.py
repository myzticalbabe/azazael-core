# coding: utf-8
"""WORMZ must not index its own BIBL output (2026-10-31 balloon).

The defect this pins, measured on the real tree: WORMZ writes
`BIBL/<LETTER>.md`, those files are `.md` inside its own scan root, and each one
carries `## <term>` headers that `_parse_markdown` turns into fresh
`markdown_header` entries pointing at the file it just wrote. Every pass
re-ingested the previous pass's output, so growth was quadratic in passes.
`F.md` reached 62 MB / 2,938,437 lines holding **24,990 copies of its own
header**; `E.md` reached 12 MB. A diff summary hides it: 2.9M lines read as one
large file, not as a loop.

The property that was missing is idempotence, so that is what is asserted:
run the crawler twice over unchanged input and require the lexicon and the
written files to be byte-identical.
"""
from __future__ import annotations

import sys
from pathlib import Path

import pytest

SRC = Path(__file__).resolve().parent.parent / "src"
if str(SRC) not in sys.path:
    sys.path.insert(0, str(SRC))

from CORE.WORMS.WORMZ import WORMZ, WORMZConfig  # noqa: E402

CORPUS = "# Title\n\n## Alpha\n\nfirst\n\n## Beta\n\nsecond\n"


@pytest.fixture()
def worm(tmp_path):
    """A crawler whose scan root and BIBL output are both throwaway."""
    work = tmp_path / "work"
    bibl = tmp_path / "BIBL"
    work.mkdir()
    bibl.mkdir()
    (work / "notes.md").write_text(CORPUS, encoding="utf-8")

    cfg = WORMZConfig()
    cfg.TARGET_FOLDERS = [str(work)]
    cfg.BIBL_PATH = str(bibl)
    # pytest writes tmp_path under %TEMP%, which is inside %LOCALAPPDATA%, and
    # the default skip_patterns contain "AppData" -- so every fixture file was
    # skipped and the guard was never exercised. Narrow the patterns to the ones
    # that matter here so the test measures the BIBL guard and nothing else.
    cfg.skip_patterns = ["node_modules", ".git", "__pycache__"]
    w = WORMZ(config=cfg)
    return w, work, bibl


def _snapshot(bibl: Path) -> dict:
    """Every written BIBL file, with INDEX.md's timestamp line removed.

    INDEX.md stamps `> Auto-generated by WORMZ on <iso timestamp>`, so it can
    never be byte-identical across two runs and comparing it raw would make
    this test assert the clock. Its CONTENT is compared, minus that line: the
    defect being pinned is growth, and a timestamp is churn.
    """
    out = {}
    for p in sorted(bibl.glob("*.md")):
        lines = p.read_text(encoding="utf-8").splitlines()
        kept = [ln for ln in lines if "Auto-generated by WORMZ on" not in ln]
        out[p.name] = "\n".join(kept)
    return out


def test_bibl_output_is_not_crawled(worm):
    """The guard itself: a file inside BIBL is never a crawl candidate."""
    w, work, bibl = worm
    produced = bibl / "A.md"
    produced.write_text("## Alpha\n", encoding="utf-8")

    assert w._should_skip(produced) is True
    assert w._should_crawl(produced) is False
    # A normal source file is unaffected.
    assert w._should_skip(work / "notes.md") is False
    assert w._should_crawl(work / "notes.md") is True


def test_own_output_entries_are_never_adopted(worm):
    """Defence in depth: a pre-built result from BIBL must not become knowledge."""
    w, work, bibl = worm
    self_ref = bibl / "F.md"
    result = w.crawl_file(work / "notes.md")
    # Simulate the historical loop: an entry whose provenance is our own file.
    for entry in result.terms_found:
        entry.file_path = str(self_ref)

    w._merge_results([result])
    assert w.entries == {}, "WORMZ adopted entries sourced from its own output"


def test_crawl_twice_is_idempotent(worm):
    """The whole defect in one assertion: pass 2 must not grow pass 1."""
    w, work, bibl = worm

    w.crawl_all(show_progress=False)
    first_terms = len(w.entries)
    first_files = _snapshot(bibl)
    assert first_terms > 0, "nothing was indexed, so idempotence proves nothing"
    assert first_files, "no BIBL files were written"

    w.crawl_all(show_progress=False)
    assert len(w.entries) == first_terms, (
        f"pass 2 grew the lexicon {first_terms} -> {len(w.entries)}: "
        "the crawler is indexing its own output again"
    )
    assert _snapshot(bibl) == first_files, "pass 2 changed the written BIBL files"
    # Growth, measured directly: the letter files must not gain bytes at all.
    # F.md reached 62 MB this way and every pass looked like a normal crawl.
    letter_bytes = {p.name: p.stat().st_size for p in sorted(bibl.glob("[A-Z0-9]*.md"))}
    assert letter_bytes, "no letter files were written"
    w.crawl_all(show_progress=False)
    assert {p.name: p.stat().st_size
            for p in sorted(bibl.glob("[A-Z0-9]*.md"))} == letter_bytes, (
        "a third pass changed the size of the letter files -- not idempotent")


def test_a_real_file_of_the_same_letter_is_still_indexed(worm):
    """The guard must not blind the crawler to genuine markdown headers."""
    w, work, bibl = worm
    (work / "extra.md").write_text("## Gamma\n\nthird\n", encoding="utf-8")
    w.crawl_all(show_progress=False)
    assert "Gamma" in w.entries
    assert w.entries["Gamma"].source == "markdown_header"
