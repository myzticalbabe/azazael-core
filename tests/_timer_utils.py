# coding: utf-8
"""Subprocess-based test timeout utility for 3.15t free-threading safety.

The subprocess is killed by OS-level timeout, cleanly releasing ALL locks
(no daemon-thread lock-leak cascade — root cause of Error #37's full-suite hang).

Uses a temp file for the subprocess runner (not `-c` inline) to avoid
nested-fstring escaping issues and shell quoting problems.

Usage:
    from _timer_utils import run_class_with_timeout

    try:
        run_class_with_timeout(MySlowTestClass, timeout_sec=30.0)
    except subprocess.TimeoutExpired:
        print("Timed out")
"""

import subprocess
import sys
import os
import tempfile
from pathlib import Path


def run_class_with_timeout(
    class_obj: type,
    timeout_sec: float = 30.0,
) -> tuple:
    """Run all test_* methods of *class_obj* in a subprocess with timeout.

    Returns:
        (passed, failed, skipped) tuple counting the subprocess results.
    """
    class_name = class_obj.__name__

    # Resolve file path
    mod = sys.modules.get(class_obj.__module__)
    if mod and hasattr(mod, '__file__') and mod.__file__:
        file_path = Path(mod.__file__).resolve()
    else:
        import inspect
        file_path = Path(inspect.getfile(class_obj)).resolve()

    # Write a temp runner script (clean Python, no inline escaping issues)
    runner_code = f'''# coding: utf-8
"""Temp runner for {class_name} — auto-generated by _timer_utils.py."""

import sys
import os
sys.path.insert(0, {str(file_path.parent)!r})
sys.path.insert(0, {str(file_path.parent.parent / 'src')!r})

import importlib.util
spec = importlib.util.spec_from_file_location('_test_module', {str(file_path)!r})
mod = importlib.util.module_from_spec(spec)
spec.loader.exec_module(mod)

cls = getattr(mod, {class_name!r})
inst = cls()

passed = failed = 0
for mn in sorted(dir(inst)):
    if not mn.startswith('test_'):
        continue
    try:
        getattr(inst, mn)()
        print(f'  [OK] {class_name}.{{mn}}')
        passed += 1
    except BaseException as e:
        if type(e).__name__ == 'Skip':
            print(f'  [SKIP] {class_name}.{{mn}}: {{e}}')
        else:
            print(f'  [FAIL] {class_name}.{{mn}}: {{e}}')
            failed += 1

sys.exit(failed)
'''

    # Write to temp file
    fd, tmp_path = tempfile.mkstemp(suffix='.py', prefix=f'_run_{class_name}_')
    try:
        with os.fdopen(fd, 'w', encoding='utf-8') as f:
            f.write(runner_code)

        # Run the temp file with timeout
        proc = subprocess.run(
            [sys.executable, tmp_path],
            capture_output=True, text=True, encoding="utf-8", errors="replace",
            timeout=timeout_sec,
        )

        # Parse subprocess output and print, also count results
        sub_passed = sub_failed = sub_skipped = 0
        for line in proc.stdout.splitlines():
            print(line)
            if line.startswith("  [OK]"):
                sub_passed += 1
            elif line.startswith("  [FAIL]"):
                sub_failed += 1
            elif line.startswith("  [SKIP]"):
                sub_skipped += 1

        if proc.stderr:
            for line in proc.stderr.splitlines():
                if "UserWarning" not in line:
                    print(f"  [STDERR] {line}")

        if proc.returncode != 0:
            print(f"  [SUB] {class_name}: subprocess exited with code {proc.returncode}")

        print(f"  [{class_name}] Passed: {sub_passed}, Failed: {sub_failed}, Skipped: {sub_skipped}")

        return (sub_passed, sub_failed, sub_skipped)

    finally:
        # Clean up temp file
        try:
            os.unlink(tmp_path)
        except OSError:
            pass
